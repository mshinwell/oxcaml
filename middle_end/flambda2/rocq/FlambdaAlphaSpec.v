(* Alpha-equivalence: that an expression stands for its alpha-equivalence
   class.

   This file is to be reviewed: [compose_renaming] and [inverse_renaming]
   against [Renaming.compose] and [Permutation.inverse], the rules of
   [alpha_equivalent], and the statements.

   FlambdaNominalSpec.v gives the renamings, their action on expressions
   and the free names. Here are the facts that make that a (partial) theory
   of nominal sets and the expressions, up to [alpha_equivalent], its
   name abstractions:
   - the renamings act as a group: the identity, composition and inverses
     ([rename_expr_identity_statement] and the two after it);
   - the free names are equivariant, as relations
     ([var_free_equivariant_statement], [cont_free_equivariant_statement])
     and as the functions of FlambdaBindersSpec.v
     ([free_variables_equivariant_statement],
     [free_continuations_equivariant_statement]), and so are the three
     conditions on binders of that file: a renaming keeps code closed,
     binders distinct and names in scope;
   - alpha-equivalence is the congruence generated by renaming a bound
     name, or the bound names of a whole expression: the least equivalence
     preserved by every context that relates a binder with its scope to
     its image under a renaming fixing the free names of the two. The
     rules for binders are those of FlambdaNominalSpec.v, read as the
     definition of when two name abstractions are equal. Each takes, as
     there, that the code bound in what is renamed is closed; the rule
     for the binders of code ([Alpha_code]) has no other condition.
     Kinds, arities and metadata have no names in them:
     alpha-equivalent expressions have the same ones;
   - alpha-equivalence is equivariant, and alpha-equivalent expressions
     have the same free names, so the action and the support are those of
     the classes ([alpha_equivalent_equivariant_statement],
     [alpha_equivalent_free_names_statement]). The same holds of the
     free names as functions, and alpha-equivalent expressions satisfy
     the same of the three conditions on binders
     ([alpha_equivalent_code_closed_statement] and the two after it),
     so those are conditions on the classes;
   - alpha-equivalent expressions behave alike under every pair of
     environments ([alpha_equivalent_sound_statement]): the semantics, and
     with it [expr_equivalent] and [expr_refines], is one of the classes.
     This is the sense in which an expression represents its class, there
     being no type of classes.

   Alpha-equivalence is defined by its generators. The definition by
   recursion on the two expressions is the comparison of
   FlambdaCompareSpec.v ([expr_eqb]): FlambdaCompareAlphaSpec.v says that
   it is an equivalence relation and contains [alpha_equivalent].

   [rename_variables_equivalent_statement] is the equivariance of
   execution in the variables, for a renaming that fixes the free
   continuations. The general statement, of every renaming and of the
   machine itself, is in FlambdaEquivarianceSpec.v.

   The proofs are in FlambdaAlphaProofs.v, which needs no review. *)

From Stdlib Require Import ZArith List.
From OxCamlStdlib Require Import OxCamlLogic OxCamlList.
From OxCamlFlambda2 Require Import FlambdaModel FlambdaMapSpec
  FlambdaBindersSpec FlambdaSemanticsSpec FlambdaContextSpec
  FlambdaNominalSpec.
Import ListNotations.

(* ======================================================================== *)
(* The renamings act as a group                                             *)
(* ======================================================================== *)

(* [Renaming.compose ~second ~first]. *)
Definition compose_renaming (second first : renaming) : renaming :=
  Renaming (variable_permutation second ++ variable_permutation first)
    (continuation_permutation second ++ continuation_permutation first).

Definition inverse_renaming (r : renaming) : renaming :=
  Renaming (rev (variable_permutation r)) (rev (continuation_permutation r)).

Definition rename_expr_identity_statement : Prop :=
  ∀ e : expr, rename_expr identity_renaming e = e.

Definition rename_expr_compose_statement : Prop :=
  ∀ (second first : renaming) (e : expr),
    rename_expr (compose_renaming second first) e
    = rename_expr second (rename_expr first e).

Definition rename_expr_inverse_statement : Prop :=
  ∀ (r : renaming) (e : expr),
    rename_expr (inverse_renaming r) (rename_expr r e) = e.

(* ======================================================================== *)
(* The free names are equivariant                                           *)
(* ======================================================================== *)

Definition var_free_equivariant_statement : Prop :=
  ∀ (r : renaming) (x : variable) (e : expr),
    var_free_in_expr (rename_variable r x) (rename_expr r e)
    <-> var_free_in_expr x e.

Definition cont_free_equivariant_statement : Prop :=
  ∀ (r : renaming) (k : continuation) (e : expr),
    cont_free_in_expr (rename_continuation r k) (rename_expr r e)
    <-> cont_free_in_expr k e.

(* The same of the free names as functions (FlambdaBindersSpec.v), which
   look into code: the free names of a renamed term are the images of the
   free names of the term, in the same order. *)
Definition free_variables_equivariant_statement : Prop :=
  ∀ (r : renaming) (e : expr),
    free_variables_of_expr (rename_expr r e)
    = map (rename_variable r) (free_variables_of_expr e).

Definition free_continuations_equivariant_statement : Prop :=
  ∀ (r : renaming) (e : expr),
    free_continuations_of_expr (rename_expr r e)
    = map (rename_continuation r) (free_continuations_of_expr e).

(* So a renaming keeps each of the three conditions on binders: code that
   is closed stays closed, binders that are distinct stay distinct, and a
   unit whose names are in scope stays so with its two continuations
   renamed. *)
Definition code_closed_equivariant_statement : Prop :=
  ∀ (r : renaming) (e : expr),
    code_closed (rename_expr r e) = code_closed e.

Definition binders_distinct_equivariant_statement : Prop :=
  ∀ (r : renaming) (e : expr),
    binders_distinct (rename_expr r e) = binders_distinct e.

Definition names_in_scope_equivariant_statement : Prop :=
  ∀ (r : renaming) (unit_return unit_exn : continuation) (e : expr),
    names_in_scope (rename_continuation r unit_return)
      (rename_continuation r unit_exn) (rename_expr r e)
    = names_in_scope unit_return unit_exn e.

(* ======================================================================== *)
(* Alpha-equivalence                                                        *)
(* ======================================================================== *)

Inductive alpha_equivalent : expr -> expr -> Prop :=
  | Alpha_refl (e : expr) : alpha_equivalent e e
  | Alpha_sym (e e' : expr) : alpha_equivalent e e' -> alpha_equivalent e' e
  | Alpha_trans (e e' e'' : expr) :
    alpha_equivalent e e' -> alpha_equivalent e' e'' ->
    alpha_equivalent e e''
  | Alpha_context (c : context) (e e' : expr) :
    alpha_equivalent e e' -> alpha_equivalent (plug c e) (plug c e')
  (* A renaming that fixes the free names of an expression moves only its
     bound names. The code of the expression is closed, here and in the
     rules below. *)
  | Alpha_rename (r : renaming) (e : expr) :
    code_closed e = true ->
    (∀ x : variable, var_free_in_expr x e -> rename_variable r x = x) ->
    (∀ k : continuation,
      cont_free_in_expr k e -> rename_continuation r k = k) ->
    alpha_equivalent e (rename_expr r e)
  (* The variable of a [Let], whose scope is the body. *)
  | Alpha_let (r : renaming) (x : variable) (kind : flambda_kind)
      (defining_expr : named) (body : expr) :
    code_closed body = true ->
    (∀ y : variable,
      y <> x -> var_free_in_expr y body -> rename_variable r y = y) ->
    (∀ k : continuation,
      cont_free_in_expr k body -> rename_continuation r k = k) ->
    alpha_equivalent (Let x kind defining_expr body)
      (Let (rename_variable r x) kind defining_expr (rename_expr r body))
  (* The continuation of a non-recursive [Let_cont], whose scope is the
     body. *)
  | Alpha_let_cont (r : renaming) (k : continuation)
      (handler : continuation_handler) (body : expr) :
    code_closed body = true ->
    (∀ y : variable, var_free_in_expr y body -> rename_variable r y = y) ->
    (∀ k' : continuation,
      k' <> k -> cont_free_in_expr k' body -> rename_continuation r k' = k')
    ->
    alpha_equivalent (Let_cont_non_recursive k handler body)
      (Let_cont_non_recursive (rename_continuation r k) handler
         (rename_expr r body))
  (* The parameters of a handler, whose scope is the handler. *)
  | Alpha_handler (r : renaming) (k : continuation) (params : list variable)
      (metadata : handler_metadata) (handler body : expr) :
    code_closed handler = true ->
    (∀ y : variable,
      y ∉ params -> var_free_in_expr y handler -> rename_variable r y = y) ->
    (∀ k' : continuation,
      cont_free_in_expr k' handler -> rename_continuation r k' = k') ->
    alpha_equivalent
      (Let_cont_non_recursive k (Handler params metadata handler) body)
      (Let_cont_non_recursive k
         (rename_handler r (Handler params metadata handler)) body)
  (* The same for a handler of a recursive [Let_cont]. *)
  | Alpha_recursive_handler (r : renaming)
      (before : list (continuation * continuation_handler))
      (k : continuation) (params : list variable)
      (metadata : handler_metadata) (handler : expr)
      (after : list (continuation * continuation_handler)) (body : expr) :
    code_closed handler = true ->
    (∀ y : variable,
      y ∉ params -> var_free_in_expr y handler -> rename_variable r y = y) ->
    (∀ k' : continuation,
      cont_free_in_expr k' handler -> rename_continuation r k' = k') ->
    alpha_equivalent
      (Let_cont_recursive
         (before ++ (k, Handler params metadata handler) :: after) body)
      (Let_cont_recursive
         (before
          ++ (k, rename_handler r (Handler params metadata handler)) :: after)
         body)
  (* The binders of code: its parameters, [my_closure] and its return and
     exception continuations, whose scope is its body. Closed code has no
     free name, so there is nothing for the renaming to fix. *)
  | Alpha_code (r : renaming) (before : list static_binding) (id : code_id)
      (c : code) (after : list static_binding) (body : expr) :
    code_is_closed c = true ->
    alpha_equivalent (Let_static (before ++ Bind_code id c :: after) body)
      (Let_static (before ++ Bind_code id (rename_code r c) :: after) body).

(* The continuations of a recursive [Let_cont] need no rule of their own:
   they are bound names of the whole expression ([Alpha_rename]). *)
Definition alpha_let_cont_recursive_statement : Prop :=
  ∀ (r : renaming) (handlers : list (continuation * continuation_handler))
    (body : expr),
    code_closed (Let_cont_recursive handlers body) = true ->
    (∀ y : variable,
      var_free_in_expr y (Let_cont_recursive handlers body) ->
      rename_variable r y = y) ->
    (∀ k : continuation,
      cont_free_in_expr k (Let_cont_recursive handlers body) ->
      rename_continuation r k = k) ->
    alpha_equivalent (Let_cont_recursive handlers body)
      (Let_cont_recursive (rename_handlers r handlers) (rename_expr r body)).

Definition alpha_equivalent_equivariant_statement : Prop :=
  ∀ (r : renaming) (e e' : expr),
    alpha_equivalent e e' ->
    alpha_equivalent (rename_expr r e) (rename_expr r e').

Definition alpha_equivalent_free_names_statement : Prop :=
  ∀ e e' : expr,
    alpha_equivalent e e' ->
    (∀ x : variable, var_free_in_expr x e <-> var_free_in_expr x e')
    ∧ (∀ k : continuation,
        cont_free_in_expr k e <-> cont_free_in_expr k e').

(* The same of the free names as functions, which look into code. *)
Definition alpha_equivalent_free_variables_statement : Prop :=
  ∀ e e' : expr,
    alpha_equivalent e e' ->
    same_names (free_variables_of_expr e) (free_variables_of_expr e').

Definition alpha_equivalent_free_continuations_statement : Prop :=
  ∀ e e' : expr,
    alpha_equivalent e e' ->
    same_names (free_continuations_of_expr e)
      (free_continuations_of_expr e').

(* So the three conditions on binders are conditions on the classes:
   alpha-equivalent expressions have their code closed together, their
   binders distinct together (no rule relates a binder that repeats a
   name to one that does not), and their names in scope together. *)
Definition alpha_equivalent_code_closed_statement : Prop :=
  ∀ e e' : expr, alpha_equivalent e e' -> code_closed e = code_closed e'.

Definition alpha_equivalent_binders_distinct_statement : Prop :=
  ∀ e e' : expr,
    alpha_equivalent e e' -> binders_distinct e = binders_distinct e'.

Definition alpha_equivalent_names_in_scope_statement : Prop :=
  ∀ (unit_return unit_exn : continuation) (e e' : expr),
    alpha_equivalent e e' ->
    names_in_scope unit_return unit_exn e
    = names_in_scope unit_return unit_exn e'.

Definition alpha_equivalent_sound_statement : Prop :=
  ∀ e e' : expr, alpha_equivalent e e' -> expr_equivalent e e'.

(* ======================================================================== *)
(* Execution is equivariant in the variables                                *)
(* ======================================================================== *)

Definition rename_env (r : renaming) (vars : env) : env :=
  map (fun '(x, v) => (rename_variable r x, v)) vars.

(* Renaming an expression and the environment of its variables together
   does not change its behaviour, for a renaming that fixes the free
   continuations, which are observed. The code of the expression is
   closed. *)
Definition rename_variables_equivalent_statement : Prop :=
  ∀ (r : renaming) (e : expr) (vars : env) (conts : cont_env)
    (statics : static_env),
    code_closed e = true ->
    (∀ k : continuation,
      cont_free_in_expr k e -> rename_continuation r k = k) ->
    equivalent (State e vars conts statics)
      (State (rename_expr r e) (rename_env r vars) conts statics).
