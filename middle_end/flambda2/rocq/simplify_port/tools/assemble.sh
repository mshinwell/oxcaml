# assemble.sh FILE.v DONOR.ml EXTRACTED.ml : writes on standard output the
# file that the port keeps in extracted/: the header of the donor (its first
# comment), one comment that says where the file comes from, the OCaml text
# that the .v file carries between a line "(*OCAML" and a line "OCAML*)",
# what Rocq extracted, as Rocq wrote it, and the OCaml text that the .v file
# carries between a line "(*OCAML-END" and a line "OCAML-END*)". Nothing of
# Rocq's text is changed. It follows no file of the compiler.
set -e
v=$1; donor=$2; out=$3
if head -1 "$donor" | grep -q '^(\*\*\*'; then
  sed -n '1,/\*\*\*)$/p' "$donor"
  echo
fi
d=${donor#../../}
# A .v file whose OCaml text also copies lines of another file of the
# compiler says so on a line "(* ALSO-FOLLOWS: PATH, lines N-M *)"; the
# comment below then names that file too.
also=$(sed -n 's/^(\* ALSO-FOLLOWS: \(.*\) \*)$/   Its OCaml text also copies \1./p' "$v")
cat <<END
(* Extracted by Rocq from middle_end/flambda2/rocq/simplify_port/$v,
   which follows middle_end/flambda2/$d function by function.
${also:+$also
}   Do not edit this file: change the .v file and run make in
   middle_end/flambda2/rocq/simplify_port. *)

END
awk '/^\(\*OCAML$/ {on=1; next} /^OCAML\*\)$/ {on=0; print ""; next} on {print}' "$v"
cat "$out"
awk '/^\(\*OCAML-END$/ {on=1; print ""; next} /^OCAML-END\*\)$/ {on=0; next} on {print}' "$v"
