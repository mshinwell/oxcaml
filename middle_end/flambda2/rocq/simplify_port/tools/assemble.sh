# assemble.sh FILE.v DONOR.ml DIRECT.ml : writes on standard output the file
# that the port keeps in extracted/: the header of the donor (its first
# comment), one comment that says where the file comes from, the OCaml text
# that the .v file carries between a line "(*OCAML" and a line "OCAML*)", and
# the direct-style code. It follows no file of the compiler.
set -e
v=$1; donor=$2; direct=$3
if head -1 "$donor" | grep -q '^(\*\*\*'; then
  sed -n '1,/\*\*\*)$/p' "$donor"
  echo
fi
d=${donor#../../}
cat <<END
(* Extracted by Rocq from middle_end/flambda2/rocq/simplify_port/$v,
   which follows middle_end/flambda2/$d function by function; the monad of
   the Rocq text is removed. Do not edit this file: change the .v file and
   run make in middle_end/flambda2/rocq/simplify_port. *)

END
awk '/^\(\*OCAML$/ {on=1; next} /^OCAML\*\)$/ {on=0; print ""; next} on {print}' "$v"
cat "$direct"
