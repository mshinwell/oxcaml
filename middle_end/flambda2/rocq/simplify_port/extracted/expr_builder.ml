  match Upwards_env.find_continuation_shortcut uenv cont0 with
  | Some shortcut -> (
    match Continuation_shortcut.to_alias shortcut with
    | Some cont1 -> Exn_continuation.with_exn_handler exn_cont cont1
    | None -> exn_cont)
  | None -> exn_cont

