(** val rewrite_fixed_arity_continuation0 : Upwards_acc.t -> cont_or_apply_cont
    -> Apply_cont_rewrite_id.t -> [ `Unarized ] Flambda_arity.t ->
    rewrite_fixed_arity_continuation0_result coq_M **)

let rewrite_fixed_arity_continuation0 uacc cont_or_apply_cont0 use_id arity =
  let uenv = Upwards_acc.uenv uacc in
  let specialize_if_needed =
   fun cont0 ->
    Port_monad.try_with
      (fun _ ->
        Continuation_callsite_map.find cont0 use_id
          (Upwards_acc.specialization_map uacc))
      Port_monad.not_found
      (fun _ -> cont0)
  in
  let cont0, cont_or_apply_cont1 =
    (fun f__1 f__2 x__0 ->
      match (x__0 : cont_or_apply_cont) with
      | Continuation x__1 -> f__1 x__1
      | Apply_cont x__1 -> f__2 x__1)
      (fun cont0 ->
        let cont1 = specialize_if_needed cont0 in
        cont1, (fun x__1 -> (Continuation x__1 : cont_or_apply_cont)) cont1)
      (fun apply_cont ->
        let cont0 = specialize_if_needed (Apply_cont.continuation apply_cont) in
        let apply_cont0 = Apply_cont.with_continuation apply_cont cont0 in
        cont0, (fun x__1 -> (Apply_cont x__1 : cont_or_apply_cont)) apply_cont0)
      cont_or_apply_cont0
  in
  let shortcut_this_continuation_if_possible =
   fun _ ->
    (fun f__1 f__2 x__0 ->
      match (x__0 : cont_or_apply_cont) with
      | Continuation x__1 -> f__1 x__1
      | Apply_cont x__1 -> f__2 x__1)
      (fun cont1 ->
        (fun x__1 ->
          (This_continuation x__1 : rewrite_fixed_arity_continuation0_result))
          (apply_continuation_aliases uenv cont1))
      (fun apply_cont ->
        (fun x__1 ->
          (Apply_cont x__1 : rewrite_fixed_arity_continuation0_result))
          (apply_continuation_shortcuts uenv apply_cont))
      cont_or_apply_cont1
  in
  match Upwards_env.find_apply_cont_rewrite uenv cont0 with
  | Some rewrite ->
    if Apply_cont_rewrite.does_nothing rewrite
    then
      let arity_in_rewrite = Apply_cont_rewrite.original_params_arity rewrite in
      let () =
        if not (Flambda_arity.equal_ignoring_subkinds arity arity_in_rewrite)
        then
          Misc.fatal_errorf
            "Arity %a provided to fixed-arity-wrapper addition function does \
             not match arity %a in rewrite:@ %a"
            Flambda_arity.print arity Flambda_arity.print arity_in_rewrite
            Apply_cont_rewrite.print rewrite
        else ()
      in
      shortcut_this_continuation_if_possible ()
    else
      let new_wrapper =
       fun params expr free_names0 cost_metrics_of_handler0 ->
        let cont1 =
          (fun x__1 x__2 x__3 -> Continuation.create ?sort:x__1 ?name:x__2 x__3)
            None None ()
        in
