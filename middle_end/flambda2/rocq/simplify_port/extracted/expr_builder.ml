          Rebuilt_expr.Continuation_handler.create
            (Upwards_acc.are_rebuilding_terms uacc)
            params expr free_names0 false false
        in
        let free_names_of_handler0 =
          ListLabels.fold_left
            (fun free_names1 param ->
              Name_occurrences.remove_var free_names1
                (Bound_parameter.var param))
            free_names0
            (Bound_parameters.to_list params)
        in
        (fun x__1 ->
          (New_wrapper x__1 : rewrite_fixed_arity_continuation0_result))
          { cont = cont1;
            handler = handler0;
            free_names_of_handler = free_names_of_handler0;
            cost_metrics_of_handler = cost_metrics_of_handler0
          }
      in
      (fun f__1 f__2 x__0 ->
        match (x__0 : cont_or_apply_cont) with
        | Continuation x__1 -> f__1 x__1
        | Apply_cont x__1 -> f__2 x__1)
        (fun _ ->
          let params =
            List.map
              (fun kind ->
                let param_var =
                  (fun x__1 x__2 x__3 ->
                    Variable.create ?user_visible:x__1 x__2 x__3)
                    None "param"
                    (Flambda_kind.With_subkind.kind kind)
                in
                let param_var_duid = Flambda_debug_uid.none in
                Bound_parameter.create param_var kind param_var_duid)
              (Flambda_arity.unarized_components arity)
          in
          let args = List.map Bound_parameter.simple params in
          let params0 = Bound_parameters.create params in
          let apply_cont =
            (fun x__1 x__2 x__3 x__4 ->
              Apply_cont.create ?trap_action:x__1 x__2 x__3 x__4)
              None cont0 args Debuginfo.none
          in
          let ctx = Apply_cont_rewrite.Apply_expr args in
          (fun f__1 f__2 f__3 x__0 ->
            match (x__0 : rewrite_apply_cont_result) with
            | Invalid { message = x__1 } -> f__1 x__1
            | Apply_cont x__1 -> f__2 x__1
            | Expr x__1 -> f__3 x__1)
            (fun message ->
              (fun x__1 ->
                (Invalid { message = x__1 }
                  : rewrite_fixed_arity_continuation0_result))
                message)
            (fun apply_cont0 ->
              let is_cold =
                Upwards_env.is_cold_continuation uenv
                  (Apply_cont.continuation apply_cont0)
              in
              let cost_metrics0 =
                Cost_metrics.from_size (Code_size.apply_cont apply_cont0)
              in
              new_wrapper params0
                (Rebuilt_expr.create_apply_cont is_cold apply_cont0)
                (Apply_cont.free_names apply_cont0)
                cost_metrics0)
            (fun build_expr ->
              let expr, cost_metrics0, free_names0 =
                build_expr (fun apply_cont0 ->
                    let is_cold =
                      Upwards_env.is_cold_continuation uenv
                        (Apply_cont.continuation apply_cont0)
                    in
