(** val apply_projection : t -> Symbol_projection.t -> Simple.t option coq_M **)

let apply_projection t0 proj =
  let symbol = Symbol_projection.symbol proj in
  let matching_defining_exprs =
    ListLabels.filter_map
      (fun definition ->
        if Definition_.binds_symbol definition symbol
        then Some definition
        else None)
      t0.definitions
  in
  match matching_defining_exprs with
  | [] -> None
  | matched_defining_expr :: l -> (
    match l with
    | [] ->
      let typing_env0, ty =
        Symbol.Map.find symbol
          (Definition_.types_of_symbols matched_defining_expr)
      in
      let meet_shortcut =
        (fun f__1 f__2 x__0 ->
          match (x__0 : Symbol_projection.Projection.t) with
          | Symbol_projection.Projection.Block_load
              { index = x__1; block_shape = x__2 } ->
            f__1 x__1 x__2
          | Symbol_projection.Projection.Project_value_slot
              { project_from = x__1; value_slot = x__2 } ->
            f__2 x__1 x__2)
          (fun index _ ->
            let field_kind =
              Flambda_kind.With_subkind.kind (Symbol_projection.kind proj)
            in
            T.meet_block_field_simple typing_env0 Name_mode.normal field_kind ty
              index)
          (fun _ value_slot ->
            T.meet_project_value_slot_simple typing_env0 Name_mode.normal ty
              value_slot)
          (Symbol_projection.projection proj)
      in
      (fun f__1 f__2 f__3 x__0 ->
        match (x__0 : _ T.meet_shortcut) with
        | T.Known_result x__1 -> f__1 x__1
        | T.Need_meet -> f__2 ()
        | T.Invalid -> f__3 ())
        (fun simple -> Some simple)
        (fun _ ->
          Misc.fatal_errorf
            "Symbol projection@ %a@ produced [Need_meet]:@ type is@ %a@ in \
             env:@ %a"
            Symbol_projection.print proj T.print ty T.Typing_env.print
            typing_env0)
        (fun _ ->
          Misc.fatal_errorf
            "Symbol projection@ %a@ produced [Invalid],@ environment is:@ %a"
            Symbol_projection.print proj T.Typing_env.print typing_env0)
        meet_shortcut
    | _ :: _ ->
      Misc.fatal_errorf
        "Symbol projection@ %a@ matches more than one constant in:@ %a"
        Symbol_projection.print proj print t0)

