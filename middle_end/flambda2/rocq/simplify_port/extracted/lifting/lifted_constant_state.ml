(** val fold : t -> 'a1 -> ('a1 -> LC.t -> 'a1 coq_M) -> 'a1 coq_M **)

let fold t0 init f =
  let rec loop init0 t1 =
    (fun f__1 f__2 f__3 f__4 x__0 ->
      match x__0 with
      | Empty -> f__1 ()
      | Leaf x__1 -> f__2 x__1
      | Leaf_array { ts = x__1 } -> f__3 x__1
      | Union { t1 = x__1; t2 = x__2 } -> f__4 x__1 x__2)
      (fun _ -> init0)
      (fun const -> f init0 const)
      (fun ts -> ArrayLabels.fold_left f init0 ts)
      (fun t2 t3 ->
        let init1 = loop init0 t3 in
        loop init1 t2)
      t1
  in
  loop init t0

