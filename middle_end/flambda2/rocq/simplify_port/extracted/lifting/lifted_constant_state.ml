(** val singleton : LC.t -> t coq_M **)

let singleton const = Leaf const

(** val singleton_list_of_constants : LC.t list -> t coq_M **)

let singleton_list_of_constants constants =
  match constants with
  | [] -> empty
  | constant :: l -> (
    match l with
    | [] -> singleton constant
    | _ :: _ -> (fun x__1 -> Leaf_array { ts = x__1 }) (Array.of_list constants)
    )

