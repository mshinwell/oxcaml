(** val build_dep_graph : t -> (CIS.Set.t CIS.Lmap.t * LC.t CIS.Map.t) coq_M **)

let build_dep_graph t0 =
  fold t0 (CIS.Lmap.empty, CIS.Map.empty) (fun pat ->
      let dep_graph, code_id_or_symbol_to_const = pat in
      fun lifted_constant ->
        ListLabels.fold_left
          (fun pat0 ->
            let dep_graph0, code_id_or_symbol_to_const0 = pat0 in
            fun definition ->
              let free_names =
                let free_names = LC.Definition.free_names definition in
                (fun f__1 f__2 f__3 x__0 ->
                  match (x__0 : LC.Definition.descr) with
                  | LC.Definition.Code x__1 -> f__1 x__1
                  | LC.Definition.Set_of_closures
                      { typing_env = x__1;
                        closure_symbols_with_types = x__2;
                        symbol_projections = x__3
                      } ->
                    f__2 x__1 x__2 x__3
                  | LC.Definition.Block_like
                      { symbol = x__1;
                        typing_env = x__2;
                        ty = x__3;
                        symbol_projections = x__4
                      } ->
                    f__3 x__1 x__2 x__3 x__4)
                  (fun _ -> free_names)
                  (fun _ closure_symbols_with_types _ ->
                    ListLabels.fold_left
                      (fun free_names0 pat1 ->
                        let symbol, _ = pat1 in
                        Name_occurrences.add_symbol free_names0 symbol
                          Name_mode.normal)
                      free_names
                      (Function_slot.Lmap.data closure_symbols_with_types))
                  (fun _ _ _ _ -> free_names)
                  (LC.Definition.descr definition)
              in
              let free_syms = Name_occurrences.symbols free_names in
              let free_code_ids =
                Name_occurrences.code_ids_and_newer_version_of_code_ids
                  free_names
              in
              let deps =
                CIS.Set.union
                  (CIS.set_of_symbol_set free_syms)
                  (CIS.set_of_code_id_set free_code_ids)
              in
              let being_defined =
                Bound_static.everything_being_defined_as_list
                  (LC.Definition.bound_static definition)
              in
              List.fold_left
                (fun pat1 ->
                  let dep_graph1, code_id_or_symbol_to_const1 = pat1 in
                  fun being_defined0 ->
                    let dep_graph2 =
                      CIS.Lmap.add being_defined0 deps dep_graph1
                    in
                    let code_id_or_symbol_to_const2 =
                      CIS.Map.add being_defined0
                        (Lifted_constant.create_definition definition)
                        code_id_or_symbol_to_const1
                    in
                    dep_graph2, code_id_or_symbol_to_const2)
                (dep_graph0, code_id_or_symbol_to_const0)
                being_defined)
          (dep_graph, code_id_or_symbol_to_const)
          (LC.definitions lifted_constant))

(** val remove_values_not_in_domain : CIS.Set.t CIS.Lmap.t -> CIS.Set.t
    CIS.Lmap.t coq_M **)

let remove_values_not_in_domain m =
  let domain =
    CIS.Lmap.fold
      (fun value _ domain -> CIS.Set.add value domain)
      m CIS.Set.empty
  in
  CIS.Lmap.map
    (fun values ->
      CIS.Set.filter (fun value -> CIS.Set.mem value domain) values)
    m

type sort_result = { innermost_first : LC.t array }

(** val innermost_first : sort_result -> LC.t array **)

let innermost_first s = s.innermost_first

(** val sort0 : t -> sort_result coq_M **)

let sort0 t0 =
  let lifted_constants_dep_graph, code_id_or_symbol_to_const =
    build_dep_graph t0
  in
  let lifted_constants_dep_graph0 =
    remove_values_not_in_domain lifted_constants_dep_graph
  in
  let innermost_first0 =
    ArrayLabels.map
      (fun group ->
        let code_id_or_symbols =
          match group with
          | SCC_lifted_constants.Has_loop code_id_or_symbols ->
            code_id_or_symbols
          | SCC_lifted_constants.No_loop code_id_or_symbol ->
            code_id_or_symbol :: []
        in
        let _, lifted_constants =
          ListLabels.fold_left
            (fun acc code_id_or_symbol ->
              let already_seen, definitions = acc in
              if CIS.Set.mem code_id_or_symbol already_seen
              then acc
              else
                let lifted_constant =
                  CIS.Map.find code_id_or_symbol code_id_or_symbol_to_const
                in
                let already_seen0 =
                  let bound_static = LC.bound_static lifted_constant in
                  CIS.Set.union
                    (Bound_static.everything_being_defined bound_static)
                    already_seen
                in
                already_seen0, lifted_constant :: definitions)
            (CIS.Set.empty, []) code_id_or_symbols
        in
        LC.concat lifted_constants)
      (SCC_lifted_constants
       .stable_connected_components_sorted_from_roots_to_leaf
         (CIS.Lmap.bindings lifted_constants_dep_graph0))
  in
  { innermost_first = innermost_first0 }

(** val sort : t -> sort_result coq_M **)

let sort t0 =
  (fun f__1 f__2 f__3 f__4 x__0 ->
    match x__0 with
    | Empty -> f__1 ()
    | Leaf x__1 -> f__2 x__1
    | Leaf_array { ts = x__1 } -> f__3 x__1
    | Union { t1 = x__1; t2 = x__2 } -> f__4 x__1 x__2)
    (fun _ -> { innermost_first = [||] })
    (fun const -> { innermost_first = (fun x__1 -> [| x__1 |]) const })
    (fun _ -> sort0 t0)
    (fun _ _ -> sort0 t0)
    t0
