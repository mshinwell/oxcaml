(** val refine_decision_based_on_arg_types_at_uses : U.pass ->
    Apply_cont_rewrite_id.Set.t -> Apply_cont_rewrite_id.Set.t ->
    Target_system.Machine_width.t -> int -> Continuation_uses.arg_at_use
    Apply_cont_rewrite_id.Map.t -> U.decision -> (U.decision *
    Apply_cont_rewrite_id.Set.t) coq_M **)

let refine_decision_based_on_arg_types_at_uses pass0 rewrite_ids_seen0
    rewrites_ids_known_as_invalid0 machine_width nth_arg arg_type_by_use_id
    decision =
  match decision with
  | U.Unbox _ ->
    Apply_cont_rewrite_id.Map.fold
      (fun rewrite_id arg_at_use0 pat ->
        let decision0, invalids = pat in
        if
          Apply_cont_rewrite_id.Set.mem rewrite_id rewrite_ids_seen0
          || Apply_cont_rewrite_id.Set.mem rewrite_id
               rewrites_ids_known_as_invalid0
        then decision0, invalids
        else
          let typing_env_at_use = arg_at_use0.Continuation_uses.typing_env in
          let arg_type_at_use = arg_at_use0.Continuation_uses.arg_type in
          let unboxed_arg =
            Port_monad.match_exn
              (fun _ ->
                (fun x__1 x__2 x__3 x__4 ->
                  TE.get_alias_then_canonical_simple_exn x__1
                    ?min_name_mode:x__2 ?name_mode_of_existing_simple:x__3 x__4)
                  typing_env_at_use (Some Name_mode.normal) None arg_type_at_use)
              Port_monad.not_found
              (fun _ ->
                (fun x__1 ->
                  (Unboxing_epa.Added_by_wrapper_at_rewrite_use
                     { nth_arg = x__1 }
                    : Unboxing_epa.unboxed_arg))
                  nth_arg)
              (fun simple -> Unboxing_epa.Available simple)
          in
          Port_monad.try_with
            (fun _ ->
              let decision1 =
                Unboxing_epa.compute_extra_args_for_one_decision_and_use pass0
                  rewrite_id typing_env_at_use machine_width unboxed_arg
                  decision0
              in
              decision1, invalids)
            ( (fun () -> Unboxing_epa.Invalid_apply_cont),
              function Unboxing_epa.Invalid_apply_cont -> Some () | _ -> None )
            (fun _ ->
              decision0, Apply_cont_rewrite_id.Set.add rewrite_id invalids))
      arg_type_by_use_id
      (decision, rewrites_ids_known_as_invalid0)
  | U.Do_not_unbox _ -> decision, rewrites_ids_known_as_invalid0

module List_ = struct
  (** val fold_left3 : ('a1 -> 'a2 -> 'a3 -> 'a4 -> 'a1 coq_M) -> 'a1 -> 'a2
      list -> 'a3 list -> 'a4 list -> 'a1 coq_M **)

  let rec fold_left3 f accu l1 l2 l3 =
    match l1 with
    | [] -> (
      match l2 with
      | [] -> (
        match l3 with [] -> accu | _ :: _ -> invalid_arg "List.fold_left3")
      | _ :: _ -> invalid_arg "List.fold_left3")
    | a1 :: l4 -> (
      match l2 with
      | [] -> invalid_arg "List.fold_left3"
      | a2 :: l5 -> (
        match l3 with
        | [] -> invalid_arg "List.fold_left3"
        | a3 :: l6 -> fold_left3 f (f accu a1 a2 a3) l4 l5 l6))
end

(** val make_do_not_unbox_decisions : Bound_parameters.t -> Decisions.t coq_M **)

let make_do_not_unbox_decisions params =
  let decisions0 =
    List.map
      (fun param0 -> param0, U.Do_not_unbox U.Unboxing_not_requested)
      (Bound_parameters.to_list params)
  in
  { Decisions.decisions = decisions0;
    Decisions.rewrite_ids_seen = Apply_cont_rewrite_id.Set.empty;
    Decisions.rewrites_ids_known_as_invalid = Apply_cont_rewrite_id.Set.empty
  }

type continuation_arg_types =
  | Recursive
  | Non_recursive of Continuation_uses.arg_types_by_use_id

(** val make_decisions_ : continuation_arg_types -> DE.t -> Bound_parameters.t
    -> T.t list -> (DE.t * Decisions.t) coq_M **)

let make_decisions_ continuation_arg_types0 denv params params_types =
  let params0 = Bound_parameters.to_list params in
  let continuation_is_recursive, arg_types_by_use_id =
    match continuation_arg_types0 with
    | Recursive ->
      true, List.map (fun _ -> Apply_cont_rewrite_id.Map.empty) params0
    | Non_recursive arg_types_by_use_id -> false, arg_types_by_use_id
  in
  let empty = Apply_cont_rewrite_id.Set.empty in
  let _, denv0, rev_decisions, seen, invalids =
    List_.fold_left3
      (fun pat ->
        let nth, denv0, rev_decisions, seen, invalids = pat in
        fun param0 param_type arg_type_by_use_id ->
          let decision =
            Optimistic_unboxing_decision.make_optimistic_decision 0
              continuation_is_recursive (DE.typing_env denv0) param_type
          in
          let decision0, invalids0 =
            if continuation_is_recursive
            then decision, invalids
            else
              let machine_width = DE.machine_width denv0 in
              let decision0, invalids0 =
                refine_decision_based_on_arg_types_at_uses U.Filter empty
                  invalids machine_width nth arg_type_by_use_id decision
              in
              let decision1 =
                Is_unboxing_beneficial.filter_non_beneficial_decisions decision0
              in
              decision1, invalids0
          in
          let denv1 =
            Build_unboxing_denv.denv_of_decision denv0 (BP.var param0) decision0
          in
          let seen0 =
            match seen with
            | Some s ->
              let () =
                assert (
                  Apply_cont_rewrite_id.Map.for_all
                    (fun id _ -> Apply_cont_rewrite_id.Set.mem id s)
                    arg_type_by_use_id)
              in
              s
            | None ->
              Apply_cont_rewrite_id.Map.fold
                (fun id _ acc -> Apply_cont_rewrite_id.Set.add id acc)
                arg_type_by_use_id empty
          in
          nth + 1, denv1, decision0 :: rev_decisions, Some seen0, invalids0)
      (0, denv, [], None, Apply_cont_rewrite_id.Set.empty)
      params0 params_types arg_types_by_use_id
  in
  let rewrite_ids_seen0 = match seen with Some s -> s | None -> empty in
  let decisions0 = List.combine params0 (List.rev rev_decisions) in
  ( denv0,
    { Decisions.decisions = decisions0;
      Decisions.rewrite_ids_seen = rewrite_ids_seen0;
      Decisions.rewrites_ids_known_as_invalid = invalids
    } )

(** val make_decisions : continuation_arg_types -> DE.t -> Bound_parameters.t ->
    T.t list -> (DE.t * Decisions.t) coq_M **)

let make_decisions continuation_arg_types0 denv params params_types =
  (fun x__1 x__2 x__3 x__4 ->
    Profile.record_call_with_counters ?accumulate:x__1 x__2 x__3 x__4)
    (Some true)
    (fun pat ->
      let _, t0 = pat in
      let { Decisions.decisions = decisions0;
            Decisions.rewrite_ids_seen = _;
            Decisions.rewrites_ids_known_as_invalid = _
          } =
        t0
      in
      let counters = Profile.Counters.create () in
      List.fold_left
        (fun counters0 pat0 ->
          let _, decision = pat0 in
          match decision with
          | U.Unbox _ -> Profile.Counters.incr "unbox" counters0
          | U.Do_not_unbox d -> (
            match d with
            | U.Not_beneficial -> Profile.Counters.incr "do_not_unbox" counters0
            | U.Max_depth_exceeded ->
              Profile.Counters.incr "max_depth_exceeded" counters0
            | U.Incomplete_parameter_type ->
              Profile.Counters.incr "do_not_unbox" counters0
            | U.Not_enough_information_at_use ->
              Profile.Counters.incr "do_not_unbox" counters0
            | U.Not_of_kind_value -> counters0
            | U.Unboxing_not_requested -> counters0
            | U.All_fields_invalid ->
              Profile.Counters.incr "do_not_unbox" counters0))
        counters decisions0)
    "make_unboxing_decisions"
    (fun _ -> make_decisions_ continuation_arg_types0 denv params params_types)

(** val compute_extra_params_and_args : Target_system.Machine_width.t ->
    Decisions.t -> Continuation_uses.arg_types_by_use_id -> EPA.t -> EPA.t coq_M
    **)

let compute_extra_params_and_args machine_width pat =
  let { Decisions.decisions = decisions0;
        Decisions.rewrite_ids_seen = rewrite_ids_seen0;
        Decisions.rewrites_ids_known_as_invalid = rewrites_ids_known_as_invalid0
      } =
    pat
  in
  fun arg_types_by_use_id existing_extra_params_and_args ->
    let _, extra_params_and_args, _ =
      List.fold_left2
        (fun pat0 ->
          let nth, extra_params_and_args, invalids = pat0 in
          fun arg_type_by_use_id pat1 ->
            let _, decision = pat1 in
            let decision0, invalids0 =
              refine_decision_based_on_arg_types_at_uses
                U.Compute_all_extra_args rewrite_ids_seen0 invalids
                machine_width nth arg_type_by_use_id decision
            in
            let extra_params_and_args0 =
              Unboxing_epa.add_extra_params_and_args extra_params_and_args
                invalids0 decision0
            in
            nth + 1, extra_params_and_args0, invalids0)
        (0, existing_extra_params_and_args, rewrites_ids_known_as_invalid0)
        arg_types_by_use_id decisions0
    in
    extra_params_and_args
