type do_not_unbox_reason =
  | Not_beneficial
  | Max_depth_exceeded
  | Incomplete_parameter_type
  | Not_enough_information_at_use
  | Not_of_kind_value
  | Unboxing_not_requested
  | All_fields_invalid

module Extra_param_and_args = struct
  type t =
    { param : Variable.t;
      param_debug_uid : Flambda_debug_uid.t;
      args :
        Continuation_extra_params_and_args.Extra_arg.t
        Apply_cont_rewrite_id.Map.t
    }

  (** val param : t -> Variable.t **)

  let param t0 = t0.param

  (** val param_debug_uid : t -> Flambda_debug_uid.t **)

  let param_debug_uid t0 = t0.param_debug_uid

  (** val args : t -> Continuation_extra_params_and_args.Extra_arg.t
      Apply_cont_rewrite_id.Map.t **)

  let args t0 = t0.args

  (** val create : string -> Flambda_debug_uid.t -> Flambda_kind.t -> t coq_M **)

  let create name debug_uid kind =
    { param =
        (fun x__1 x__2 x__3 -> Variable.create ?user_visible:x__1 x__2 x__3)
          None name kind;
      param_debug_uid = debug_uid;
      args = Apply_cont_rewrite_id.Map.empty
    }

  (** val update_param_args : t -> Apply_cont_rewrite_id.t ->
      Continuation_extra_params_and_args.Extra_arg.t -> t coq_M **)

  let update_param_args t0 rewrite_id extra_arg =
    let () = assert (not (Apply_cont_rewrite_id.Map.mem rewrite_id t0.args)) in
    let args0 = Apply_cont_rewrite_id.Map.add rewrite_id extra_arg t0.args in
    (fun t x__1 -> { t with args = x__1 }) t0 args0

  (** val print : Format.formatter -> t -> unit coq_M **)

  let print fmt pat =
    let { param = param0; param_debug_uid = _; args = _ } = pat in
    Format.fprintf fmt "@[<hv 1>(@[<hov>(param %a)@]@ @[<v 2>(args@ <...>)@])@]"
      Variable.print param0
end

type field_decision =
  { epa : Extra_param_and_args.t;
    decision : decision;
    kind : Flambda_kind.With_subkind.t
  }

and unboxing_decision =
  | Unique_tag_and_size of
      { tag : Tag.t;
        shape : K.Block_shape.t;
        fields : field_decision list
      }
  | Variant of
      { tag : Extra_param_and_args.t;
        const_ctors : const_ctors_decision;
        fields_by_tag :
          (K.Block_shape.t * field_decision list) Tag.Scannable.Map.t
      }
  | Closure_single_entry of
      { function_slot : Function_slot.t;
        vars_within_closure : field_decision Value_slot.Map.t
      }
  | Number of Flambda_kind.Naked_number_kind.t * Extra_param_and_args.t

and const_ctors_decision =
  | Zero
  | At_least_one of
      { is_int : Extra_param_and_args.t;
        ctor : decision
      }

and decision =
  | Unbox of unboxing_decision
  | Do_not_unbox of do_not_unbox_reason

type decisions_ =
  { decisions : (Bound_parameter.t * decision) list;
    rewrite_ids_seen : Apply_cont_rewrite_id.Set.t;
    rewrites_ids_known_as_invalid : Apply_cont_rewrite_id.Set.t
  }

(** val decisions : decisions_ -> (Bound_parameter.t * decision) list **)

let decisions d = d.decisions

(** val rewrite_ids_seen : decisions_ -> Apply_cont_rewrite_id.Set.t **)

let rewrite_ids_seen d = d.rewrite_ids_seen

(** val rewrites_ids_known_as_invalid : decisions_ ->
    Apply_cont_rewrite_id.Set.t **)

let rewrites_ids_known_as_invalid d = d.rewrites_ids_known_as_invalid

type pass =
  | Filter
  | Compute_all_extra_args

(** val print_do_not_unbox_reason : Format.formatter -> do_not_unbox_reason ->
    unit coq_M **)

let print_do_not_unbox_reason ppf = function
  | Not_beneficial -> Format.fprintf ppf "not_beneficial"
  | Max_depth_exceeded -> Format.fprintf ppf "max_depth_exceeded"
  | Incomplete_parameter_type -> Format.fprintf ppf "incomplete_parameter_type"
  | Not_enough_information_at_use ->
    Format.fprintf ppf "not_enough_information_at_use"
  | Not_of_kind_value -> Format.fprintf ppf "not_of_kind_value"
  | Unboxing_not_requested -> Format.fprintf ppf "unboxing_not_requested"
  | All_fields_invalid -> Format.fprintf ppf "all_fields_invalid"

(** val print_decision : Format.formatter -> decision -> unit coq_M **)

let rec print_decision ppf = function
  | Unbox u ->
    (fun f__1 f__2 f__3 f__4 x__0 ->
      match (x__0 : unboxing_decision) with
      | Unique_tag_and_size { tag = x__1; shape = x__2; fields = x__3 } ->
        f__1 x__1 x__2 x__3
      | Variant { tag = x__1; const_ctors = x__2; fields_by_tag = x__3 } ->
        f__2 x__1 x__2 x__3
      | Closure_single_entry
          { function_slot = x__1; vars_within_closure = x__2 } ->
        f__3 x__1 x__2
      | Number (x__1, x__2) -> f__4 x__1 x__2)
      (fun tag shape fields ->
        Format.fprintf ppf
          "@[<v 1>(unique_tag_and_size@ @[<h>(static_tag %a)@]@ @[<h>(shape \
           %a)@]@ @[<hv 2>(fields@ %a)@])@]"
          Tag.print tag Flambda_kind.Block_shape.print shape
          print_fields_decisions fields)
      (fun tag const_ctors fields_by_tag ->
        Format.fprintf ppf
          "@[<v 2>(variant@ @[<hov>(tag %a)@]@ @[<hv 2>(const_ctors@ %a)@]@ \
           @[<v 2>(fields_by_tag@ %a)@])@]"
          Extra_param_and_args.print tag print_const_ctor_num const_ctors
          (Tag.Scannable.Map.print (fun ppf0 pat ->
               let _, fields = pat in
               print_fields_decisions ppf0 fields))
          fields_by_tag)
      (fun function_slot vars_within_closure ->
        Format.fprintf ppf
          "@[<hov 1>(closure_single_entry@ @[<hov>(function_slot@ %a)@]@ @[<hv \
           2>(value_slots@ %a)@])@]"
          Function_slot.print function_slot
          (Value_slot.Map.print print_field_decision)
          vars_within_closure)
      (fun kind epa ->
        Format.fprintf ppf
          "@[<hv 1>(number@ @[<h>(kind %a)@]@ @[<hv 1>(var %a)@])@]"
          Flambda_kind.Naked_number_kind.print kind Extra_param_and_args.print
          epa)
      u
  | Do_not_unbox reason ->
    Format.fprintf ppf "@[<hov 1>(do_not_unbox@ %a)@]" print_do_not_unbox_reason
      reason

(** val print_field_decision : Format.formatter -> field_decision -> unit coq_M
    **)

and print_field_decision ppf field_decision0 =
  (fun x__0 f__1 ->
    let { epa = x__1; decision = x__2; kind = x__3 } = x__0 in
    f__1 x__1 x__2 x__3) field_decision0 (fun epa decision kind ->
      Format.fprintf ppf
        "@[<hv 1>(@,\
         @[<hov 1>(var %a)@]@ @[<hv 1>(decision@ %a)@]@ (kind@ %a))@]"
        Extra_param_and_args.print epa print_decision decision
        Flambda_kind.With_subkind.print kind)

(** val print_fields_decisions : Format.formatter -> field_decision list -> unit
    coq_M **)

and print_fields_decisions ppf l =
  let pp_sep = Format.pp_print_space in
  Format.fprintf ppf "%a"
    ((fun x__1 x__2 x__3 x__4 ->
       Format.pp_print_list ?pp_sep:x__1 x__2 x__3 x__4)
       (Some pp_sep) print_field_decision)
    l

(** val print_const_ctor_num : Format.formatter -> const_ctors_decision -> unit
    coq_M **)

and print_const_ctor_num ppf const_ctors =
  (fun f__1 f__2 x__0 ->
    match (x__0 : const_ctors_decision) with
    | Zero -> f__1 ()
    | At_least_one { is_int = x__1; ctor = x__2 } -> f__2 x__1 x__2)
    (fun _ -> Format.fprintf ppf "no_const_ctors")
    (fun is_int ctor ->
      Format.fprintf ppf
        "@[<hov 1>(const_ctors@ @[<hov 1>(is_int@ %a)@]@ @[<hov 1>(ctor@ \
         %a)@])@]"
        Extra_param_and_args.print is_int print_decision ctor)
    const_ctors

(** val print : Format.formatter -> decisions_ -> unit coq_M **)

let print ppf pat =
  let { decisions = decisions0;
        rewrite_ids_seen = rewrite_ids_seen0;
        rewrites_ids_known_as_invalid = rewrites_ids_known_as_invalid0
      } =
    pat
  in
  let pp_sep = Format.pp_print_space in
  let aux =
   fun ppf0 pat0 ->
    let param0, decision = pat0 in
    Format.fprintf ppf0 "@[<hov 1>(%a@ %a)@]" Bound_parameter.print param0
      print_decision decision
  in
  Format.fprintf ppf
    "@[<hov 1>(@[<hov 1>(decisions@ %a)@]@ @[<hov 1>(rewrite_ids_seen@ %a)@]@ \
     @[<hov 1>(rewrites_ids_known_as_invalid@ %a)@])@]"
    ((fun x__1 x__2 x__3 x__4 ->
       Format.pp_print_list ?pp_sep:x__1 x__2 x__3 x__4)
       (Some pp_sep) aux)
    decisions0 Apply_cont_rewrite_id.Set.print rewrite_ids_seen0
    Apply_cont_rewrite_id.Set.print rewrites_ids_known_as_invalid0

