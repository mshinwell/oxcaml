(** val rename_params : t -> t coq_M **)

let rename_params t0 =
  let params0 = Bound_parameters.rename t0.params in
  let params_renaming = Bound_parameters.renaming t0.params params0 in
  let lifted_params0, lifted_params_renaming =
    Lifted_cont_params.rename t0.lifted_params
  in
  let renaming = Renaming.compose lifted_params_renaming params_renaming in
  let handler0 = Flambda.Expr.apply_renaming t0.handler renaming in
  { cont = t0.cont;
    params = params0;
    lifted_params = lifted_params0;
    handler = handler0;
    is_exn_handler = t0.is_exn_handler;
    can_be_lifted = t0.can_be_lifted;
    is_cold = t0.is_cold
  }
