(** val print : Format.formatter -> t -> unit coq_M **)

let print ppf pat =
  let { cont = cont0;
        params = params0;
        lifted_params = lifted_params0;
        handler = handler0;
        is_exn_handler = is_exn_handler0;
        can_be_lifted = can_be_lifted0;
        is_cold = is_cold0
      } =
    pat
  in
  Format.fprintf ppf
    "@[<hov 1>(@[<hv 1>(cont@ %a)@]@ @[<hv 1>(params@ %a)@]@ @[<hv \
     1>(lifted_params@ %a)@]@ @[<hv 1>(is_exn_handler@ %b)@]@ @[<hv \
     1>(can_be_lifted@ %b)@]@ @[<hv 1>(is_cold@ %b)@]@ @[<hv 1>(handler@ \
     %a)@]@ )@]"
