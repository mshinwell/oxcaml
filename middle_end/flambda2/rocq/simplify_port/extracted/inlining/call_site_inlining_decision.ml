(** val make_decision0 : DA.t -> Flambda.Import.Expr.t
    Simplify_common.expr_simplifier -> Simplified_expr.t Simplify_common.rebuild
    -> FT.t -> Flambda.Import.Apply.t -> [ `Complex ] Flambda_arity.t ->
    Call_site_inlining_decision_type.t coq_M **)

let make_decision0 dacc simplify_expr rebuild_expr function_type apply
    return_arity =
  let must_inline = DE.must_inline (DA.denv dacc) in
  let fail_if_must_inline =
   fun _ ->
    if must_inline
    then
      Misc.fatal_errorf
        "Deciding not to inline an [Apply], but the replay_history says we \
         should inline.@ Replay_history: %a"
        Replay_history.print
        (DE.replay_history (DA.denv dacc))
    else ()
  in
  let do_not_inline =
   fun decision ->
    let () = fail_if_must_inline () in
    decision
  in
  let rec_info = get_rec_info dacc function_type in
  let inlined = Flambda.Import.Apply.inlined apply in
  match inlined with
  | Inlined_attribute.Always_inlined _ ->
    Port_monad.match_exn
      (fun _ ->
        DE.find_code_metadata_exn (DA.denv dacc) (FT.code_id function_type))
      Port_monad.not_found
      (fun _ -> do_not_inline Call_site_inlining_decision_type.Missing_code)
      (fun code_metadata ->
        let code_present =
         fun _ ->
          Port_monad.match_exn
            (fun _ ->
              DE.find_code_exn (DA.denv dacc)
                (Code_metadata.code_id code_metadata))
            Port_monad.not_found
            (fun _ ->
              Misc.fatal_errorf
                "[DE.find_code_metadata_exn] found a code metadata, but \
                 [DE.find_code_exn] returns Not_found for code_id %a"
                Code_id.print
                (Code_metadata.code_id code_metadata))
            Code_or_metadata.code_present
        in
        let inline_if_code_present =
         fun decision ->
          if code_present ()
          then decision
          else do_not_inline Call_site_inlining_decision_type.Missing_code
        in
        let unrolling_depth =
          Simplify_rec_info_expr.known_remaining_unrolling_depth dacc rec_info
        in
        match unrolling_depth with
        | Some n ->
          if n = 0
          then
            do_not_inline
              Call_site_inlining_decision_type.Unrolling_depth_exceeded
          else
            inline_if_code_present
              Call_site_inlining_decision_type.Continue_unrolling
        | None -> (
          let apply_inlining_state =
            Flambda.Import.Apply.inlining_state apply
          in
          let recursive = Code_metadata.recursive code_metadata in
          if Inlining_state.is_depth_exceeded apply_inlining_state
          then
            do_not_inline
              Call_site_inlining_decision_type.Max_inlining_depth_exceeded
          else
            let policy =
              match inlined with
              | Inlined_attribute.Always_inlined _ -> (
                match recursive with
                | Recursive.Non_recursive -> `Always
                | Recursive.Recursive -> `Unroll 1)
              | Inlined_attribute.Hint_inlined -> (
                match recursive with
                | Recursive.Non_recursive -> `Always
                | Recursive.Recursive -> `Unroll 1)
              | Inlined_attribute.Forward_inlined -> assert false
              | Inlined_attribute.Never_inlined -> assert false
              | Inlined_attribute.Unroll (to_, _) -> `Unroll to_
              | Inlined_attribute.Default_inlined -> `Heuristic
            in
            match policy with
            | `Heuristic ->
              let max_rec_depth =
                Flambda_features.Inlining.max_rec_depth
                  (Flambda_features.Inlining.Round (DE.round (DA.denv dacc)))
              in
              if
                Simplify_rec_info_expr.depth_may_exceed dacc rec_info
                  max_rec_depth
              then
                do_not_inline
                  Call_site_inlining_decision_type.Recursion_depth_exceeded
              else if must_inline
              then
                match
                  Replay_history.replay_inlining_decision
                    (DE.replay_history (DA.denv dacc))
                with
                | Replay_history.Still_recording ->
                  Misc.fatal_errorf
                    "Internal assumption broken: DE.says must_inline\n\
                    \                  (presumably because of the replay \
                     history), but the replay history is still recoding."
                | Replay_history.Replayed decision ->
                  if code_present ()
                  then
                    Call_site_inlining_decision_type
                    .Replay_history_says_must_inline
                      decision
                  else
                    Misc.fatal_errorf
                      "Replay history says we should inline %a, but its code \
                       is not present"
                      Code_id.print
                      (Code_metadata.code_id code_metadata)
              else
                might_inline dacc apply code_metadata function_type
                  simplify_expr rebuild_expr return_arity
            | `Unroll unroll_to ->
              if Simplify_rec_info_expr.can_unroll dacc rec_info
              then
                inline_if_code_present
                  (Call_site_inlining_decision_type.Begin_unrolling unroll_to)
              else
                do_not_inline
                  Call_site_inlining_decision_type.Unrolling_depth_exceeded
            | `Always ->
              inline_if_code_present
                Call_site_inlining_decision_type.Attribute_always))
  | Inlined_attribute.Hint_inlined ->
    Port_monad.match_exn
      (fun _ ->
        DE.find_code_metadata_exn (DA.denv dacc) (FT.code_id function_type))
      Port_monad.not_found
      (fun _ -> do_not_inline Call_site_inlining_decision_type.Missing_code)
      (fun code_metadata ->
        let code_present =
         fun _ ->
          Port_monad.match_exn
            (fun _ ->
              DE.find_code_exn (DA.denv dacc)
                (Code_metadata.code_id code_metadata))
            Port_monad.not_found
            (fun _ ->
              Misc.fatal_errorf
                "[DE.find_code_metadata_exn] found a code metadata, but \
                 [DE.find_code_exn] returns Not_found for code_id %a"
                Code_id.print
                (Code_metadata.code_id code_metadata))
            Code_or_metadata.code_present
        in
        let inline_if_code_present =
         fun decision ->
          if code_present ()
          then decision
          else do_not_inline Call_site_inlining_decision_type.Missing_code
        in
        let unrolling_depth =
          Simplify_rec_info_expr.known_remaining_unrolling_depth dacc rec_info
        in
        match unrolling_depth with
        | Some n ->
          if n = 0
          then
