(** val add : t -> Apply_cont_rewrite_id.Set.t -> Bound_parameter.t ->
    Extra_arg.t Apply_cont_rewrite_id.Map.t -> t coq_M **)

let add t0 invalids extra_param extra_args0 =
  (fun f__1 f__2 x__0 ->
    match x__0 with
    | Empty -> f__1 ()
    | Non_empty { extra_params = x__1; extra_args = x__2 } -> f__2 x__1 x__2)
    (fun _ ->
      let extra_params0 = Bound_parameters.create (extra_param :: []) in
      let valid_extra_args =
        Apply_cont_rewrite_id.Map.map
          (fun extra_args1 -> Or_invalid.Ok (extra_args1 :: []))
          extra_args0
      in
      let extra_args1 =
        Apply_cont_rewrite_id.Set.fold
          (fun id map ->
            Apply_cont_rewrite_id.Map.add id Or_invalid.Invalid map)
          invalids valid_extra_args
      in
      (fun (x__1, x__2) -> Non_empty { extra_params = x__1; extra_args = x__2 })
        (extra_params0, extra_args1))
    (fun extra_params0 already_extra_args ->
      let extra_params1 = Bound_parameters.cons extra_param extra_params0 in
      let extra_args1 =
        Apply_cont_rewrite_id.Map.merge
          (fun id already_extra_args0 extra_arg ->
            match already_extra_args0 with
            | Some y -> (
              match y with
              | Or_invalid.Ok already_extra_args1 -> (
                match extra_arg with
                | Some extra_arg0 ->
                  if Apply_cont_rewrite_id.Set.mem id invalids
                  then Some Or_invalid.Invalid
                  else Some (Or_invalid.Ok (extra_arg0 :: already_extra_args1))
                | None ->
                  if Apply_cont_rewrite_id.Set.mem id invalids
                  then Some Or_invalid.Invalid
                  else
                    Misc.fatal_errorf
                      "[Extra Params and Args] Existing Apply_cont_rewrite_id \
                       (%a) missing for:\n\
                       new param: %a\n\
                       new args: %a\n\
                       new invalids: %a\n\
                       existing epa: %a"
                      Apply_cont_rewrite_id.print id Bound_parameter.print
                      extra_param
                      (Apply_cont_rewrite_id.Map.print Extra_arg.print)
                      extra_args0 Apply_cont_rewrite_id.Set.print invalids print
                      t0)
              | Or_invalid.Invalid -> (
                match extra_arg with
                | Some _ -> Some Or_invalid.Invalid
                | None ->
                  if Apply_cont_rewrite_id.Set.mem id invalids
                  then Some Or_invalid.Invalid
                  else
                    Misc.fatal_errorf
                      "[Extra Params and Args] Existing Apply_cont_rewrite_id \
                       (%a) missing for:\n\
                       new param: %a\n\
                       new args: %a\n\
                       new invalids: %a\n\
                       existing epa: %a"
                      Apply_cont_rewrite_id.print id Bound_parameter.print
                      extra_param
                      (Apply_cont_rewrite_id.Map.print Extra_arg.print)
                      extra_args0 Apply_cont_rewrite_id.Set.print invalids print
                      t0))
            | None -> (
              match extra_arg with
              | Some _ ->
                Misc.fatal_errorf
                  "[Extra Params and Args] Unexpected New \
                   Apply_cont_rewrite_id (%a) for:\n\
                   new param: %a\n\
                   new args: %a\n\
                   new invalids: %a\n\
                   existing epa: %a"
                  Apply_cont_rewrite_id.print id Bound_parameter.print
                  extra_param
                  (Apply_cont_rewrite_id.Map.print Extra_arg.print)
                  extra_args0 Apply_cont_rewrite_id.Set.print invalids print t0
              | None -> None))
          already_extra_args extra_args0
      in
      (fun (x__1, x__2) -> Non_empty { extra_params = x__1; extra_args = x__2 })
        (extra_params1, extra_args1))
    t0

