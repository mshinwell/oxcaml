(** val add_args_for_all_params : t -> Apply_cont_rewrite_id.t -> Extra_arg.t
    list -> t coq_M **)

let add_args_for_all_params t0 apply_cont_rewrite_id new_args =
  let error =
   fun _ -> Misc.fatal_errorf "Mismatched number of extra params and extra args"
  in
  (fun f__1 f__2 x__0 ->
    match x__0 with
    | Empty -> f__1 ()
    | Non_empty { extra_params = x__1; extra_args = x__2 } -> f__2 x__1 x__2)
    (fun _ -> match new_args with [] -> t0 | _ :: _ -> error ())
    (fun extra_params0 extra_args0 ->
      if
        not
          (List.compare_lengths new_args
             (Bound_parameters.to_list extra_params0)
          = 0)
      then error ()
      else
        let extra_args1 =
          Apply_cont_rewrite_id.Map.add apply_cont_rewrite_id
            (Or_invalid.Ok new_args) extra_args0
        in
        (fun (x__1, x__2) ->
          Non_empty { extra_params = x__1; extra_args = x__2 })
          (extra_params0, extra_args1))
    t0
