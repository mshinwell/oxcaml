(** val concat : t -> t -> t coq_M **)

let concat outer inner =
  (fun f__1 f__2 x__0 ->
    match x__0 with
    | Empty -> f__1 ()
    | Non_empty { extra_params = x__1; extra_args = x__2 } -> f__2 x__1 x__2)
    (fun _ -> inner)
    (fun t1_extra_params t1_extra_args ->
      (fun f__1 f__2 x__0 ->
        match x__0 with
        | Empty -> f__1 ()
        | Non_empty { extra_params = x__1; extra_args = x__2 } -> f__2 x__1 x__2)
        (fun _ -> outer)
        (fun t2_extra_params t2_extra_args ->
          let extra_args0 =
            Apply_cont_rewrite_id.Map.merge
              (fun id extra_args1 extra_args2 ->
                match extra_args1 with
                | Some y -> (
                  match y with
                  | Or_invalid.Ok extra_args3 -> (
                    match extra_args2 with
                    | Some y0 -> (
                      match y0 with
                      | Or_invalid.Ok extra_args4 ->
                        Some (Or_invalid.Ok (extra_args3 @ extra_args4))
                      | Or_invalid.Invalid -> Some Or_invalid.Invalid)
                    | None ->
                      Misc.fatal_errorf
                        "concat: mismatching domains on id %a.@\n\
                         outer: %a@\n\
                         inner: %a"
                        Apply_cont_rewrite_id.print id print outer print inner)
                  | Or_invalid.Invalid -> Some Or_invalid.Invalid)
                | None -> (
                  match extra_args2 with
                  | Some t0 -> (
                    match t0 with
                    | Or_invalid.Ok _ ->
                      Misc.fatal_errorf
                        "concat: mismatching domains on id %a.@\n\
                         outer: %a@\n\
                         inner: %a"
                        Apply_cont_rewrite_id.print id print outer print inner
                    | Or_invalid.Invalid -> Some Or_invalid.Invalid)
                  | None -> None))
              t1_extra_args t2_extra_args
          in
          (fun (x__1, x__2) ->
            Non_empty { extra_params = x__1; extra_args = x__2 })
            ( Bound_parameters.append t1_extra_params t2_extra_params,
              extra_args0 ))
        inner)
    outer

