open Port_monad

type t_simplified =
  { simplified_named : Simplified_named.t Or_invalid.t;
    try_reify : bool;
    dacc : Downwards_acc.t
  }

(** val simplified_named : t_simplified -> Simplified_named.t Or_invalid.t **)

let simplified_named t0 = t0.simplified_named

(** val try_reify : t_simplified -> bool **)

let try_reify t0 = t0.try_reify

(** val dacc : t_simplified -> Downwards_acc.t **)

let dacc t0 = t0.dacc

type t = t_simplified Simplified_named.or_rewritten

(** val create : Flambda.Named.t -> bool -> Downwards_acc.t -> t coq_M **)

let create named try_reify0 dacc0 =
  let machine_width = Downwards_env.machine_width (Downwards_acc.denv dacc0) in
  Simplified_named.Simplified
    { simplified_named = Ok (Simplified_named.create machine_width named);
      try_reify = try_reify0;
      dacc = dacc0
    }

(** val create_simplified : Simplified_named.t -> bool -> Downwards_acc.t -> t
    coq_M **)

let create_simplified simplified_named0 try_reify0 dacc0 =
  Simplified_named.Simplified
    { simplified_named = Ok simplified_named0;
      try_reify = try_reify0;
      dacc = dacc0
    }

(** val create_invalid : Downwards_acc.t -> t coq_M **)

let create_invalid dacc0 =
  Simplified_named.Simplified
    { simplified_named = Invalid; try_reify = false; dacc = dacc0 }

(** val create_unit : Downwards_acc.t -> Bound_var.t -> Flambda.Named.t -> t
    coq_M **)

let create_unit dacc0 result_var original_term =
  let machine_width = Downwards_env.machine_width (Downwards_acc.denv dacc0) in
  let ty =
    Flambda2_types.this_tagged_immediate (Target_ocaml_int.zero machine_width)
  in
  let dacc1 = Downwards_acc.add_variable dacc0 result_var ty in
  create original_term false dacc1

(** val create_unknown : Downwards_acc.t -> Bound_var.t -> Flambda_kind.t ->
    Flambda.Named.t -> t coq_M **)

let create_unknown dacc0 result_var kind original_term =
  let ty = Flambda2_types.unknown kind in
  let dacc1 = Downwards_acc.add_variable dacc0 result_var ty in
  create original_term false dacc1

(** val create_rewritten : (Flambda.Expr.t -> Flambda.Expr.t coq_M) -> t coq_M **)

let create_rewritten f = Simplified_named.Rewritten f

(** val is_invalid : t -> bool coq_M **)

let is_invalid = function
  | Simplified_named.Simplified t1 -> (
    let { simplified_named = simplified_named0; try_reify = _; dacc = _ } =
      t1
    in
    match simplified_named0 with Ok _ -> false | Invalid -> true)
  | Simplified_named.Rewritten _ -> false

(** val map_dacc : t -> (Downwards_acc.t -> Downwards_acc.t coq_M) -> t coq_M **)

let map_dacc t0 f =
  match t0 with
  | Simplified_named.Simplified t1 ->
    Simplified_named.Simplified
      { simplified_named = t1.simplified_named;
        try_reify = t1.try_reify;
        dacc = f t1.dacc
      }
  | Simplified_named.Rewritten _ -> t0
