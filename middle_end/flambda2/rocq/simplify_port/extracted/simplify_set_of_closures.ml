    if Loopify_attribute.should_loopify (Code.loopify code0)
    then
      Loopify_state.loopify
        ((fun x__1 x__2 x__3 -> Continuation.create ?sort:x__1 ?name:x__2 x__3)
           None (Some "self") ())
    else Loopify_state.do_not_loopify
  in
  let dacc_at_function_entry0 =
    dacc_inside_function context outer_dacc0 params0 my_closure my_alloc_mode
      my_depth function_slot_opt closure_bound_names_inside_function
      inlining_arguments absolute_history code_id0 return_continuation
      exn_continuation loopify_state (Code.code_metadata code0)
  in
  let dacc0 = dacc_at_function_entry0 in
  let () =
    if not (DA.no_lifted_constants dacc0)
    then
      Misc.fatal_errorf "Did not expect lifted constants in [dacc]:@ %a"
        DA.print dacc0
    else ()
  in
  let () = assert (not (DE.at_unit_toplevel (DA.denv dacc0))) in
  let my_alloc_region_duid = Flambda_debug_uid.none in
  let my_region_duid = Flambda_debug_uid.none in
  let my_ghost_region_duid = Flambda_debug_uid.none in
  let region_params =
    (fun f__1 f__2 x__0 ->
      match (x__0 : Alloc_mode.For_applications.t) with
      | Alloc_mode.For_applications.Not_alloc_stack { alloc_region = x__1 } ->
        f__1 x__1
      | Alloc_mode.For_applications.Maybe_alloc_stack
          { alloc_region = x__1; region = x__2; ghost_region = x__3 } ->
        f__2 x__1 x__2 x__3)
      (fun alloc_region ->
        Bound_parameter.create alloc_region Flambda_kind.With_subkind.region
          my_alloc_region_duid
        :: [])
      (fun alloc_region region ghost_region ->
        [ Bound_parameter.create alloc_region Flambda_kind.With_subkind.region
            my_alloc_region_duid;
          Bound_parameter.create region Flambda_kind.With_subkind.region
            my_region_duid;
          Bound_parameter.create ghost_region Flambda_kind.With_subkind.region
            my_ghost_region_duid ])
      my_alloc_mode
  in
  let my_closure_duid = Flambda_debug_uid.none in
  let my_depth_duid = Flambda_debug_uid.none in
  Port_monad.match_exn
    (fun _ ->
      C.simplify_function_body context dacc0 body return_continuation
        (Code.result_arity code0) exn_continuation loopify_state params0
