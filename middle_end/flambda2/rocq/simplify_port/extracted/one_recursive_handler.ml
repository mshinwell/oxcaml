open Port_monad

type t =
  { params : Bound_parameters.t;
    handler : Flambda.Expr.t;
    is_cold : bool
  }

(** val params : t -> Bound_parameters.t **)

let params t0 = t0.params

(** val handler : t -> Flambda.Expr.t **)

let handler t0 = t0.handler

(** val is_cold : t -> bool **)

let is_cold t0 = t0.is_cold

(** val create : Bound_parameters.t -> Flambda.Expr.t -> bool -> t coq_M **)

let create params0 handler0 is_cold0 =
  { params = params0; handler = handler0; is_cold = is_cold0 }

(** val print : Format.formatter -> t -> unit coq_M **)

let print ppf pat =
  let { params = params0; handler = handler0; is_cold = is_cold0 } = pat in
  Format.fprintf ppf
    "@[<hov 1>(@[<hv 1>(params@ %a)@]@ @[<hv 1>(is_cold@ %b)@]@ @[<hv \
     1>(handler@ %a)@])@]"
    Bound_parameters.print params0 is_cold0 Flambda.Expr.print handler0

(** val with_handler : Flambda.Expr.t -> t -> t coq_M **)

let with_handler handler0 t0 = (fun t handler -> { t with handler }) t0 handler0
