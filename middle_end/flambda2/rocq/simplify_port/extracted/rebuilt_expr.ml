(** val contents_hash_simple : Simple.t -> int coq_M **)

let contents_hash_simple simple =
  Simple.pattern_match' simple
    (fun _ coercion ->
      let has_coercion = not (Coercion.is_id coercion) in
      Hashtbl.hash (2, has_coercion))
    (fun symbol coercion ->
      let has_coercion = not (Coercion.is_id coercion) in
      Hashtbl.hash (1, Symbol.hash symbol, has_coercion))
    (fun const -> Hashtbl.hash (0, Reg_width_const.hash const))

(** val create_let : ART.t -> Bound_pattern.t -> Named.t -> t ->
    Name_occurrences.t -> t coq_M **)

let create_let are_rebuilding bound_vars defining_expr body free_names_of_body =
  if ART.do_not_rebuild_terms are_rebuilding
  then term_not_rebuilt
  else
    let contents_hash0 =
      match body.contents_hash with
      | Or_null.Null -> None
      | Or_null.This c -> (
        let { depth = depth0; structural_hash = body_hash } = c in
        let simple_expr =
         fun named_hash ->
          Some
            { depth = depth0 + 1;
              structural_hash = Hashtbl.hash (1, named_hash, body_hash)
            }
        in
        match defining_expr with
        | Flambda.Simple simple ->
          simple_expr (Hashtbl.hash (0, contents_hash_simple simple))
        | Flambda.Prim (prim, _) ->
          let args_hash =
            List.map contents_hash_simple (Flambda_primitive.args prim)
          in
          let prim0 = Flambda_primitive.without_args prim in
          simple_expr (Hashtbl.hash (1, prim0, args_hash))
        | Flambda.Set_of_closures (_, _) -> None
        | Flambda.Static_consts _ -> None
        | Flambda.Rec_info _ -> None)
    in
    create contents_hash0 body.is_cold
      (Expr.create_let
         (Let.create bound_vars defining_expr body.expr
            (Or_unknown.Known free_names_of_body)))

(** val create_apply : ART.t -> bool -> Apply.t -> t coq_M **)

let create_apply are_rebuilding is_cold0 apply =
