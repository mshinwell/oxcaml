(** val bind_no_simplification : ART.t -> (Bound_var.t, Code_size.t, Named.t)
    Port_monad.tuple3 list -> t -> Cost_metrics.t -> Name_occurrences.t -> (t,
    Cost_metrics.t, Name_occurrences.t) Port_monad.tuple3 coq_M **)

let bind_no_simplification are_rebuilding bindings body cost_metrics_of_body
    free_names_of_body =
  ListLabels.fold_left
    (fun acc binding ->
      let expr0, cost_metrics, free_names = acc in
      let var, size_of_defining_expr, defining_expr = binding in
      let expr1 =
        create_let are_rebuilding
          (Bound_pattern.singleton var)
          defining_expr expr0 free_names
      in
      let free_names0 =
        Name_occurrences.union
          (Named.free_names defining_expr)
          (Name_occurrences.remove_var free_names (Bound_var.var var))
      in
      let is_phantom = Name_mode.is_phantom (Bound_var.name_mode var) in
      let cost_metrics_of_defining_expr =
        Cost_metrics.from_size size_of_defining_expr
      in
      let cost_metrics0 =
        Cost_metrics.( + ) cost_metrics
          (Cost_metrics.increase_due_to_let_expr is_phantom
             cost_metrics_of_defining_expr)
      in
      expr1, cost_metrics0, free_names0)
    (body, cost_metrics_of_body, free_names_of_body)
    (List.rev bindings)

module Matching_for_unique_handler = struct
  (** val fail : unit -> 'a1 coq_M **)

  let fail _ =
    Port_monad.raise_
      ( (fun () -> Match_failure),
        function Match_failure -> Some () | _ -> None )
      ()

  (** val fail_if_not : bool -> unit coq_M **)

  let fail_if_not b =
    if not b
    then
      Port_monad.raise_
        ( (fun () -> Match_failure),
          function Match_failure -> Some () | _ -> None )
        ()
    else ()

  (** val fail_if_not_equal : ('a1 -> 'a2 -> bool coq_M) -> 'a1 -> 'a2 -> unit
      coq_M **)

  let fail_if_not_equal f x y = fail_if_not (f x y)

  module Match_permutable_parameters = struct
    type parameter_on_one_side =
      { kind : Flambda_kind.With_subkind.t;
        mutable matching_variable_on_other_side : Variable.t option
      }

    (** val mk_parameter_on_one_side : Flambda_kind.With_subkind.t -> Variable.t
        option -> parameter_on_one_side coq_M **)

    let mk_parameter_on_one_side =
     fun kind matching_variable_on_other_side ->
      { kind; matching_variable_on_other_side }

    (** val kind : parameter_on_one_side -> Flambda_kind.With_subkind.t **)

    let kind = fun p -> p.kind

    (** val get_matching_variable_on_other_side : parameter_on_one_side ->
        Variable.t option coq_M **)

    let get_matching_variable_on_other_side =
     fun p -> p.matching_variable_on_other_side

    (** val set_matching_variable_on_other_side : parameter_on_one_side ->
        Variable.t option -> unit coq_M **)

    let set_matching_variable_on_other_side =
     fun p v -> p.matching_variable_on_other_side <- v

    type t =
      { params1 : parameter_on_one_side HV.t;
        params2 : parameter_on_one_side HV.t
      }

    (** val params1 : t -> parameter_on_one_side HV.t **)

    let params1 t0 = t0.params1

    (** val params2 : t -> parameter_on_one_side HV.t **)

    let params2 t0 = t0.params2

    (** val matching_variable_for_param2 : t -> Bound_parameter.t -> Variable.t
        coq_M **)

    let matching_variable_for_param2 t0 param2 =
      Port_monad.match_exn
        (fun _ -> HV.find t0.params2 (Bound_parameter.var param2))
        Port_monad.not_found
        (fun _ ->
          Misc.fatal_errorf "Parameter %a is not bound on the second side"
            Bound_parameter.print param2)
        (fun binding ->
          match get_matching_variable_on_other_side binding with
          | Some var -> var
          | None -> fail ())

    (** val create : Bound_parameters.t -> Bound_parameters.t -> t coq_M **)

    let create params3 params4 =
      let () =
        if not (Bound_parameters.same_number params3 params4)
        then fail ()
        else ()
      in
      let create_mapping =
       fun params0 ->
        let table = HV.create 16 in
        let () =
          List.iter
            (fun param ->
              HV.replace table
                (Bound_parameter.var param)
                (mk_parameter_on_one_side (Bound_parameter.kind param) None))
            (Bound_parameters.to_list params0)
        in
        table
      in
      let mapping2 = create_mapping params4 in
      let mapping1 = create_mapping params3 in
      { params1 = mapping1; params2 = mapping2 }

    (** val match_variable : t -> Variable.t -> Variable.t -> unit coq_M **)

    let match_variable t0 var1 var2 =
      Port_monad.match_exn
        (fun _ -> HV.find t0.params1 var1)
        Port_monad.not_found
        (fun _ -> fail ())
        (fun binding1 ->
          match get_matching_variable_on_other_side binding1 with
          | Some var2' -> fail_if_not_equal Variable.equal var2' var2
          | None ->
            let kind1 = kind binding1 in
            Port_monad.match_exn
              (fun _ -> HV.find t0.params2 var2)
              Port_monad.not_found
              (fun _ -> fail ())
              (fun binding2 ->
                match get_matching_variable_on_other_side binding2 with
                | Some _ -> fail ()
                | None ->
                  let kind2 = kind binding2 in
                  let () =
                    fail_if_not_equal Flambda_kind.With_subkind.equal kind1
                      kind2
                  in
                  let () =
                    set_matching_variable_on_other_side binding1 (Some var2)
                  in
                  set_matching_variable_on_other_side binding2 (Some var1)))
  end

  type matching_env =
    { permutable_params1 : Match_permutable_parameters.t Variable_.Map.t;
      permutable_params2 : Match_permutable_parameters.t Variable_.Map.t
    }

  (** val permutable_params1 : matching_env -> Match_permutable_parameters.t
      Variable_.Map.t **)

  let permutable_params1 m = m.permutable_params1

  (** val permutable_params2 : matching_env -> Match_permutable_parameters.t
      Variable_.Map.t **)

  let permutable_params2 m = m.permutable_params2

  (** val match_variable : matching_env -> Variable.t -> Variable.t -> unit
      coq_M **)

  let match_variable env var1 var2 =
    match Variable.Map.find_or_null var1 env.permutable_params1 with
    | Or_null.Null ->
      let () =
        if Variable.Map.mem var2 env.permutable_params2 then fail () else ()
      in
      fail_if_not_equal Variable.equal var1 var2
    | Or_null.This permutation ->
      Match_permutable_parameters.match_variable permutation var1 var2

  (** val match_equal_and_free_names : ('a1 -> 'a1 -> bool coq_M) -> ('a1 ->
      Name_occurrences.t coq_M) -> matching_env -> 'a1 -> 'a1 -> unit coq_M **)

  let match_equal_and_free_names equal free_names env t1 t2 =
    let () = fail_if_not_equal equal t1 t2 in
    Name_occurrences.fold_variables (free_names t1) () (fun _ var ->
        match_variable env var var)

  (** val match_name : matching_env -> Name.t -> Name.t -> unit coq_M **)

  let match_name env name1 name2 =
    Name.pattern_match name1
      (fun var1 ->
        Name.pattern_match name2
          (fun var2 -> match_variable env var1 var2)
          (fun _ -> fail ()))
      (fun symbol1 -> fail_if_not_equal Name.equal name2 (Name.symbol symbol1))

  (** val match_simple : matching_env -> Simple.t -> Simple.t -> unit coq_M **)

  let match_simple env simple1 simple2 =
    Simple.pattern_match simple1
      (fun name1 coercion1 ->
        Simple.pattern_match simple2
          (fun name2 coercion2 ->
            let () =
              match_equal_and_free_names Coercion.equal Coercion.free_names env
                coercion1 coercion2
            in
            match_name env name1 name2)
          (fun _ -> fail ()))
      (fun const1 ->
        Simple.pattern_match simple2
          (fun _ _ -> fail ())
          (fun const2 -> fail_if_not_equal Reg_width_const.equal const1 const2))

  (** val match_list : ('a1 -> 'a2 -> 'a3 -> unit coq_M) -> 'a1 -> 'a2 list ->
      'a3 list -> unit coq_M **)

  let rec match_list match_elt env xs ys =
    match xs with
    | [] -> ( match ys with [] -> () | _ :: _ -> fail ())
    | x :: xs0 -> (
      match ys with
      | [] -> fail ()
      | y :: ys0 ->
        let () = match_elt env x y in
        match_list match_elt env xs0 ys0)

  (** val match_simples : matching_env -> Simple.t list -> Simple.t list -> unit
      coq_M **)

  let match_simples env simples1 simples2 =
    match_list match_simple env simples1 simples2

  (** val match_primitive : matching_env -> Flambda_primitive.t ->
      Flambda_primitive.t -> unit coq_M **)

  let match_primitive env prim1 prim2 =
    let () =
      match_equal_and_free_names Flambda_primitive.Without_args.equal
        Flambda_primitive.Without_args.free_names env
        (Flambda_primitive.without_args prim1)
        (Flambda_primitive.without_args prim2)
    in
    match_simples env
      (Flambda_primitive.args prim1)
      (Flambda_primitive.args prim2)

  (** val match_named : matching_env -> Named.t -> Named.t -> unit coq_M **)

  let match_named env named1 named2 =
    match named1 with
    | Flambda.Simple simple1 -> (
      match named2 with
      | Flambda.Simple simple2 -> match_simple env simple1 simple2
      | Flambda.Prim (_, _) -> fail ()
      | Flambda.Set_of_closures (_, _) -> fail ()
      | Flambda.Static_consts _ -> fail ()
      | Flambda.Rec_info _ -> fail ())
    | Flambda.Prim (prim1, _) -> (
      match named2 with
      | Flambda.Simple _ -> fail ()
      | Flambda.Prim (prim2, _) -> match_primitive env prim1 prim2
      | Flambda.Set_of_closures (_, _) -> fail ()
      | Flambda.Static_consts _ -> fail ()
      | Flambda.Rec_info _ -> fail ())
    | Flambda.Set_of_closures (_, _) -> fail ()
    | Flambda.Static_consts _ -> fail ()
    | Flambda.Rec_info _ -> fail ()

  (** val match_expr : matching_env -> Expr.t -> Expr.t -> unit coq_M **)

  let rec match_expr env t1 t2 =
    let descr2 = Expr.descr t2 in
    let descr1 = Expr.descr t1 in
    (fun f__1 f__2 f__3 f__4 f__5 f__6 x__0 ->
      match (x__0 : Flambda.expr_descr) with
      | Flambda.Let x__1 -> f__1 x__1
      | Flambda.Let_cont x__1 -> f__2 x__1
      | Flambda.Apply x__1 -> f__3 x__1
      | Flambda.Apply_cont x__1 -> f__4 x__1
      | Flambda.Switch x__1 -> f__5 x__1
      | Flambda.Invalid { message = x__1 } -> f__6 x__1)
      (fun let_expr1 ->
        (fun f__1 f__2 f__3 f__4 f__5 f__6 x__0 ->
          match (x__0 : Flambda.expr_descr) with
          | Flambda.Let x__1 -> f__1 x__1
          | Flambda.Let_cont x__1 -> f__2 x__1
          | Flambda.Apply x__1 -> f__3 x__1
          | Flambda.Apply_cont x__1 -> f__4 x__1
          | Flambda.Switch x__1 -> f__5 x__1
          | Flambda.Invalid { message = x__1 } -> f__6 x__1)
          (fun let_expr2 -> match_let_expr env let_expr1 let_expr2)
          (fun _ -> fail ())
          (fun _ -> fail ())
          (fun _ -> fail ())
          (fun _ -> fail ())
          (fun _ -> fail ())
          descr2)
      (fun _ -> fail ())
      (fun _ -> fail ())
      (fun apply_cont1 ->
        (fun f__1 f__2 f__3 f__4 f__5 f__6 x__0 ->
          match (x__0 : Flambda.expr_descr) with
          | Flambda.Let x__1 -> f__1 x__1
          | Flambda.Let_cont x__1 -> f__2 x__1
          | Flambda.Apply x__1 -> f__3 x__1
          | Flambda.Apply_cont x__1 -> f__4 x__1
          | Flambda.Switch x__1 -> f__5 x__1
          | Flambda.Invalid { message = x__1 } -> f__6 x__1)
          (fun _ -> fail ())
          (fun _ -> fail ())
          (fun _ -> fail ())
          (fun apply_cont2 -> match_apply_cont env apply_cont1 apply_cont2)
          (fun _ -> fail ())
          (fun _ -> fail ())
          descr2)
      (fun _ -> fail ())
      (fun _ -> fail ())
      descr1

  (** val match_let_expr : matching_env -> Let.t -> Let.t -> unit coq_M **)

  and match_let_expr env let_expr1 let_expr2 =
    let () =
      match_named env
        (Let.defining_expr let_expr1)
        (Let.defining_expr let_expr2)
    in
    Let.pattern_match let_expr1 (fun bound_pattern1 body1 ->
        Let.pattern_match let_expr2 (fun bound_pattern2 body2 ->
            match bound_pattern1 with
            | Bound_pattern.Singleton bound_var1 -> (
              match bound_pattern2 with
              | Bound_pattern.Singleton bound_var2 ->
                let body3 =
                  Expr.apply_renaming body2
                    (Renaming.add_variable Renaming.empty
                       (Bound_var.var bound_var2) (Bound_var.var bound_var1))
                in
                match_expr env body1 body3
              | Bound_pattern.Set_of_closures _ -> fail ()
              | Bound_pattern.Static _ -> fail ())
            | Bound_pattern.Set_of_closures _ -> fail ()
            | Bound_pattern.Static _ -> fail ()))

  (** val match_apply_cont : matching_env -> Apply_cont.t -> Apply_cont.t ->
      unit coq_M **)

  and match_apply_cont env apply_cont1 apply_cont2 =
    let trap_action2 = Apply_cont.trap_action apply_cont2 in
    let trap_action1 = Apply_cont.trap_action apply_cont1 in
    match trap_action1 with
    | Some _ -> fail ()
    | None -> (
      match trap_action2 with
      | Some _ -> fail ()
      | None ->
        let () =
          fail_if_not_equal Continuation.equal
            (Apply_cont.continuation apply_cont1)
            (Apply_cont.continuation apply_cont2)
        in
        match_simples env
          (Apply_cont.args apply_cont1)
          (Apply_cont.args apply_cont2))

  (** val match_permutable_continuation_handler : Bound_parameters.t -> Expr.t
      -> Bound_parameters.t -> Expr.t -> Simple.t list coq_M **)

  let match_permutable_continuation_handler params3 handler1 params4 handler2 =
    let permutation = Match_permutable_parameters.create params3 params4 in
    let create_permutable_params =
     fun params0 ->
      List.fold_left
        (fun env param ->
          Variable.Map.add (Bound_parameter.var param) permutation env)
        Variable.Map.empty
        (Bound_parameters.to_list params0)
    in
    let permutable_params3 = create_permutable_params params3 in
    let permutable_params4 = create_permutable_params params4 in
    let () =
      match_expr
        { permutable_params1 = permutable_params3;
          permutable_params2 = permutable_params4
        }
        handler1 handler2
    in
    List.map
      (fun param2 ->
        Simple.var
          (Match_permutable_parameters.matching_variable_for_param2 permutation
             param2))
      (Bound_parameters.to_list params4)

  (** val match_non_recursive_continuation_handler : bool -> Bound_parameters.t
      -> Expr.t -> Bound_parameters.t -> Expr.t -> Simple.t list coq_M **)

  let match_non_recursive_continuation_handler is_exn_handler0 params3 handler1
      params4 handler2 =
    if is_exn_handler0
    then
      let list2 = Bound_parameters.to_list params4 in
      let list1 = Bound_parameters.to_list params3 in
      match list1 with
      | [] -> fail ()
      | exn1 :: params5 -> (
        match list2 with
        | [] -> fail ()
        | exn2 :: params6 ->
          let () =
            fail_if_not_equal Flambda_kind.With_subkind.equal
              (Bound_parameter.kind exn1)
              (Bound_parameter.kind exn2)
          in
          let handler3 =
            Expr.apply_renaming handler2
              (Renaming.add_variable Renaming.empty (Bound_parameter.var exn2)
                 (Bound_parameter.var exn1))
          in
          Bound_parameter.simple exn1
          :: match_permutable_continuation_handler
               (Bound_parameters.create params5)
               handler1
               (Bound_parameters.create params6)
               handler3)
    else match_permutable_continuation_handler params3 handler1 params4 handler2
end

(** val match_continuation_handler : bool -> Bound_parameters.t -> Expr.t ->
    Bound_parameters.t -> Expr.t -> Simple.t list option coq_M **)

let match_continuation_handler is_exn_handler0 params3 handler1 params4 handler2
    =
  Port_monad.match_exn
    (fun _ ->
      Matching_for_unique_handler.match_non_recursive_continuation_handler
        is_exn_handler0 params3 handler1 params4 handler2)
    ((fun () -> Match_failure), function Match_failure -> Some () | _ -> None)
    (fun _ -> None)
    (fun args -> Some args)

module Unique_continuation_handlers = struct
  type 'a entry =
    { params : Bound_parameters.t;
      handler : Expr.t;
      is_exn_handler : bool;
      payload : 'a
    }

  (** val params : 'a1 entry -> Bound_parameters.t **)

  let params e = e.params

  (** val handler : 'a1 entry -> Expr.t **)

  let handler e = e.handler

  (** val is_exn_handler : 'a1 entry -> bool **)

  let is_exn_handler e = e.is_exn_handler

  (** val payload : 'a1 entry -> 'a1 **)

  let payload e = e.payload

  type 'a t = { hash_map : 'a entry list Numeric_types.Int.Map.t }

  (** val hash_map : 'a1 t -> 'a1 entry list Numeric_types.Int.Map.t **)

  let hash_map t0 = t0.hash_map

  (** val empty : 'a1 t **)

  let empty = { hash_map = Numeric_types.Int.Map.empty }

  (** val contents_hash : ART.t -> rebuilt_expr -> bool -> Name_occurrences.t ->
      int Or_null.t coq_M **)

  let contents_hash are_rebuilding handler0 is_exn_handler0
      free_names_without_params =
    if ART.do_not_rebuild_terms are_rebuilding
    then Or_null.null
    else
      match handler0.contents_hash with
      | Or_null.Null -> Or_null.null
      | Or_null.This c ->
        let { depth = depth0; structural_hash = structural_hash0 } = c in
        Or_null.this
          (Name_occurrences.fold_variables free_names_without_params
             (Hashtbl.hash
                (depth0, structural_hash0, Bool.hash is_exn_handler0))
             (fun hash var -> Hashtbl.hash (hash, Variable.hash var)))

  (** val add : ART.t -> Bound_parameters.t -> rebuilt_expr -> bool ->
      Name_occurrences.t -> 'a1 -> 'a1 t -> 'a1 t coq_M **)

  let add are_rebuilding params0 handler0 is_exn_handler0
      free_names_without_params value t0 =
    match
      contents_hash are_rebuilding handler0 is_exn_handler0
        free_names_without_params
    with
    | Or_null.Null -> t0
    | Or_null.This hash ->
      let entries =
        match Numeric_types.Int.Map.find_or_null hash t0.hash_map with
        | Or_null.Null -> []
        | Or_null.This entries -> entries
      in
      let entry0 =
        { params = params0;
          handler = handler0.expr;
          is_exn_handler = is_exn_handler0;
          payload = value
        }
      in
      { hash_map =
          Numeric_types.Int.Map.add hash (entry0 :: entries) t0.hash_map
      }

  (** val find_opt : ART.t -> Bound_parameters.t -> rebuilt_expr -> bool ->
      Name_occurrences.t -> 'a1 t -> ('a1 * Simple.t list) option coq_M **)

  let find_opt are_rebuilding params0 handler0 is_exn_handler0
      free_names_without_params t0 =
    match
      contents_hash are_rebuilding handler0 is_exn_handler0
        free_names_without_params
    with
    | Or_null.Null -> None
    | Or_null.This hash ->
      Option.bind
        (Numeric_types.Int.Map.find_opt hash t0.hash_map)
        (List.find_map (fun entry0 ->
             let { params = other_params;
                   handler = other_handler;
                   is_exn_handler = other_is_exn_handler;
                   payload = value
                 } =
               entry0
             in
             if Bool.equal is_exn_handler0 other_is_exn_handler
             then
               Option.map
                 (fun args -> value, args)
                 (match_continuation_handler is_exn_handler0 params0
                    handler0.expr other_params other_handler)
             else None))
end
