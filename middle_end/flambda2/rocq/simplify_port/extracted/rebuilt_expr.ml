(** val create : contents_hash_ option -> bool -> Expr.t -> t coq_M **)

let create contents_hash0 is_cold0 expr0 =
  let contents_hash1 =
    match contents_hash0 with
    | Some c ->
      let { depth = depth0; structural_hash = _ } = c in
      if depth0 >= max_hash_depth
      then Or_null.null
      else Or_null.of_option contents_hash0
    | None -> Or_null.of_option contents_hash0
  in
  { expr = expr0; is_cold = is_cold0; contents_hash = contents_hash1 }

