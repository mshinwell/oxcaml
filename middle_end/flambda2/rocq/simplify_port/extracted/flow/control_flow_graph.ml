(** val create : Continuation.t -> T.Acc.t -> t coq_M **)

let create dummy_toplevel_cont0 source_info =
  let { T.Acc.stack = _;
        T.Acc.map = map0;
        T.Acc.extra = _;
        T.Acc.lifted_constants = _;
        T.Acc.dummy_toplevel_cont = _
      } =
    source_info
  in
  let parents0 =
    Continuation.Map.filter_map
      (fun _ elt -> elt.Flow_types.Continuation_info.parent_continuation)
      map0
  in
  let children0 =
    Continuation.Map.fold
      (fun k parent acc ->
        Continuation.Map.update parent
          (fun x ->
            match x with
            | Some set -> Some (Continuation.Set.add k set)
            | None -> Some (Continuation.Set.singleton k))
          acc)
      parents0 Continuation.Map.empty
  in
  let callers0 =
    Continuation.Map.fold
      (fun caller elt acc ->
        let acc0 =
          Continuation.Map.update caller
            (fun res ->
              match res with
              | Some _ -> res
              | None -> Some Continuation.Set.empty)
            acc
        in
        let acc1 =
          Continuation.Map.update_many
            (fun _ acc_opt _ ->
              match acc_opt with
              | Some set -> Some (Continuation.Set.add caller set)
              | None -> Some (Continuation.Set.singleton caller))
            acc0 elt.Flow_types.Continuation_info.apply_cont_args
        in
        acc1)
      map0
      (Continuation.Map.singleton dummy_toplevel_cont0 Continuation.Set.empty)
  in
  { dummy_toplevel_cont = dummy_toplevel_cont0;
    callers = callers0;
    parents = parents0;
    children = children0
  }

(** val map_fold_on_children : t -> (Continuation.t -> 'a1 -> ('a1 * 'a2) coq_M)
    -> 'a1 -> 'a2 Continuation.Map.t coq_M **)

let map_fold_on_children t0 f acc =
  let { dummy_toplevel_cont = dummy_toplevel_cont0;
        callers = _;
        parents = _;
        children = children0
      } =
    t0
  in
  let rec aux k acc0 =
    let acc1, to_add = f k acc0 in
    let map0 = Continuation.Map.singleton k to_add in
    match Continuation.Map.find_or_null k children0 with
    | Null -> map0
    | This s ->
      Continuation.Set.fold
        (fun child map1 ->
          (fun x__1 x__2 x__3 x__4 ->
            Continuation.Map.disjoint_union ?eq:x__1 ?print:x__2 x__3 x__4)
            None None map1 (aux child acc1))
        s map0
  in
  aux dummy_toplevel_cont0 acc

(** val compute_available_variables : T.Acc.t -> t -> Variable.Set.t
    Continuation.Map.t coq_M **)

let compute_available_variables source_info t0 =
  map_fold_on_children t0
    (fun k acc ->
      let elt = Continuation.Map.find k source_info.Flow_types.Acc.map in
      let extra_vars =
        match
          Continuation.Map.find_or_null k source_info.Flow_types.Acc.extra
        with
        | Null -> Variable.Set.empty
        | This epa ->
          Bound_parameters.var_set
            (Continuation_extra_params_and_args.extra_params epa)
      in
      let acc0 =
        Variable.Set.union
          (Variable.Set.union acc
             (Bound_parameters.var_set elt.Flow_types.Continuation_info.params))
          extra_vars
      in
      acc0, acc0)
    Variable.Set.empty

(** val compute_added_extra_args : Variable.Set.t Continuation.Map.t -> t ->
    Variable.Set.t Continuation.Map.t coq_M **)

let compute_added_extra_args added_extra_args t0 =
  map_fold_on_children t0
    (fun k available ->
      ( Variable.Set.union (Continuation.Map.find k added_extra_args) available,
        available ))
    Variable.Set.empty

(** val fixpoint : t -> 'a1 Continuation.Map.t -> ('a1 -> 'a1 -> bool coq_M) ->
    (Continuation.t -> 'a1 -> Continuation.t -> 'a1 -> 'a1 coq_M) -> 'a1
    Continuation.Map.t coq_M **)

let fixpoint t0 init eq f =
  let components =
    G.connected_components_sorted_from_roots_to_leaf t0.callers
  in
  let res =
    Array.fold_left
      (fun res component ->
        match component with
        | G.Has_loop conts ->
          let q = Queue.create () in
          let () = List.iter (fun k -> Queue.add k q) conts in
          let q_s = ref Continuation.Set.empty in
          let cur = ref res in
          let () =
            Port_monad.while_
              (fun _ -> not (Queue.is_empty q))
              (fun _ ->
                let callee = Queue.pop q in
                let () = q_s := Continuation.Set.add callee !q_s in
                let callee_set = Continuation.Map.find callee !cur in
                let callers0 =
                  Port_monad.match_exn
                    (fun _ -> Continuation.Map.find callee t0.callers)
                    Port_monad.not_found
                    (fun _ ->
                      Misc.fatal_errorf "Callers not found for: %a"
                        Continuation.print callee)
                    (fun callers0 -> callers0)
                in
                Continuation.Set.iter
                  (fun caller ->
                    let caller_set = Continuation.Map.find caller !cur in
                    let caller_new_set =
                      f caller caller_set callee callee_set
                    in
                    if not (eq caller_set caller_new_set)
                    then
                      let () =
                        cur := Continuation.Map.add caller caller_new_set !cur
                      in
                      if Continuation.Set.mem caller !q_s
                      then
                        let () = Queue.add caller q in
                        q_s := Continuation.Set.remove caller !q_s
                      else ()
                    else ())
                  callers0)
          in
          !cur
        | G.No_loop callee -> (
          match Continuation.Map.find_or_null callee res with
          | Null -> res
          | This callee_set ->
            Continuation.Set.fold
              (fun caller res0 ->
                let caller_set = Continuation.Map.find caller res0 in
                let caller_new_set = f caller caller_set callee callee_set in
                Continuation.Map.add caller caller_new_set res0)
              (Continuation.Map.find callee t0.callers)
              res))
      init components
  in
  res

(** val extra_args_for_aliases_overapproximation : Name.Set.t -> T.Acc.t ->
    Simple.Set.t -> Dominator_graph.alias_map -> t -> Variable.Set.t
    Continuation.Map.t coq_M **)

let extra_args_for_aliases_overapproximation required_names source_info
    unboxed_blocks doms t0 =
  let available_variables = compute_available_variables source_info t0 in
  let remove_vars_in_scope_of =
   fun k var_set ->
    let elt = Continuation.Map.find k source_info.Flow_types.Acc.map in
    let res =
      Variable.Set.diff var_set (Continuation.Map.find k available_variables)
    in
    Variable.Set.diff res elt.Flow_types.Continuation_info.defined
  in
  let init =
    Continuation.Map.mapi
      (fun k elt ->
        let s =
          List.fold_left
            (fun acc param ->
              match Variable.Map.find_or_null param doms with
              | Null ->
                if Name.Set.mem (Name.var param) required_names
                then
                  Misc.fatal_errorf "Dom not found for: %a@." Variable.print
                    param
                else acc
              | This dom ->
                Simple.pattern_match' dom
                  (fun dom_var _ ->
                    if
                      Variable.equal param dom_var
                      || Simple.Set.mem dom unboxed_blocks
                    then acc
                    else Variable.Set.add dom_var acc)
                  (fun _ _ -> acc)
                  (fun _ -> acc))
            Variable.Set.empty
            (Bound_parameters.vars elt.Flow_types.Continuation_info.params)
        in
        let s0 = remove_vars_in_scope_of k s in
        s0)
      source_info.Flow_types.Acc.map
  in
  let added_extra_args =
    fixpoint t0 init Variable.Set.equal
      (fun caller caller_aliases_needed _ callee_aliases_needed ->
        Variable.Set.union caller_aliases_needed
          (remove_vars_in_scope_of caller callee_aliases_needed))
  in
  added_extra_args

(** val minimize_extra_args_for_one_continuation : T.Acc.t -> Simple.Set.t ->
    Variable.Set.t Continuation.Map.t -> Simple.t Variable_.Map.t ->
    Continuation.t -> Variable.Set.t -> T.Continuation_param_aliases.t coq_M **)

let minimize_extra_args_for_one_continuation source_info unboxed_blocks
    available_added_extra_args doms k aliases_needed =
  let available = Continuation.Map.find k available_added_extra_args in
  let extra_args_for_aliases0 = Variable.Set.diff aliases_needed available in
  let elt = Continuation.Map.find k source_info.Flow_types.Acc.map in
  let exception_handler_first_param =
    if elt.Flow_types.Continuation_info.is_exn_handler
    then
      match
        Bound_parameters.to_list elt.Flow_types.Continuation_info.params
      with
      | [] ->
        Misc.fatal_errorf
          "exception handler continuation %a must have at least one parameter"
          Continuation.print k
      | first :: _ -> Some (Bound_parameter.var first)
    else None
  in
  let extra_args_for_aliases1, exception_handler_first_param_aliased =
    match exception_handler_first_param with
    | Some exception_param -> (
      match Variable.Map.find_or_null exception_param doms with
      | Null -> extra_args_for_aliases0, Not_aliased
      | This alias ->
        Simple.pattern_match' alias
          (fun alias_var _ ->
            if Variable.equal exception_param alias_var
            then extra_args_for_aliases0, Not_aliased
            else
              ( Variable.Set.remove alias_var extra_args_for_aliases0,
                (fun (x__1, x__2) ->
                  Aliased { alias_var = x__1; exception_param = x__2 })
                  (alias_var, exception_param) ))
          (fun _ _ -> extra_args_for_aliases0, Aliased_to_a_symbol)
          (fun _ -> extra_args_for_aliases0, Aliased_to_poison))
    | None -> extra_args_for_aliases0, Not_aliased
  in
  let lets_to_introduce0 =
    (fun f__1 f__2 f__3 f__4 x__0 ->
      match x__0 with
      | Not_aliased -> f__1 ()
      | Aliased_to_poison -> f__2 ()
      | Aliased_to_a_symbol -> f__3 ()
      | Aliased { alias_var = x__1; exception_param = x__2 } -> f__4 x__1 x__2)
      (fun _ -> Variable.Lmap.empty)
      (fun _ -> Variable.Lmap.empty)
      (fun _ -> Variable.Lmap.empty)
      (fun alias exception_param ->
        Variable.Lmap.singleton alias (Simple.var exception_param))
      exception_handler_first_param_aliased
  in
  let removed_aliased_params_and_extra_params0, lets_to_introduce1 =
    List.fold_left
      (fun pat param ->
        let removed, lets_to_introduce1 = pat in
        let default =
         fun alias ->
          let removed0 = Variable.Set.add param removed in
          let lets_to_introduce2 =
            if Simple.Set.mem alias unboxed_blocks
            then lets_to_introduce1
            else Variable.Lmap.add param alias lets_to_introduce1
          in
          removed0, lets_to_introduce2
        in
        match Variable.Map.find_or_null param doms with
        | Null -> removed, lets_to_introduce1
        | This alias ->
          if Simple.equal (Simple.var param) alias
          then removed, lets_to_introduce1
          else
            (fun f__1 f__2 f__3 f__4 x__0 ->
              match x__0 with
              | Not_aliased -> f__1 ()
              | Aliased_to_poison -> f__2 ()
              | Aliased_to_a_symbol -> f__3 ()
              | Aliased { alias_var = x__1; exception_param = x__2 } ->
                f__4 x__1 x__2)
              (fun _ -> default alias)
              (fun _ -> removed, lets_to_introduce1)
              (fun _ -> removed, lets_to_introduce1)
              (fun aliased_to exception_param ->
                let is_first_exception_param =
                  Variable.equal exception_param param
                in
                if is_first_exception_param
                then removed, lets_to_introduce1
                else if Simple.equal alias (Simple.var aliased_to)
                then default (Simple.var exception_param)
                else default alias)
              exception_handler_first_param_aliased)
      (Variable.Set.empty, lets_to_introduce0)
      (Bound_parameters.vars elt.Flow_types.Continuation_info.params)
  in
  let recursive_continuation_wrapper0 =
    if
      elt.Flow_types.Continuation_info.recursive
      && not (Variable.Set.is_empty extra_args_for_aliases1)
    then T.Continuation_param_aliases.Wrapper_needed
    else T.Continuation_param_aliases.No_wrapper
  in
  let res =
    { T.Continuation_param_aliases.removed_aliased_params_and_extra_params =
        removed_aliased_params_and_extra_params0;
      T.Continuation_param_aliases.lets_to_introduce = lets_to_introduce1;
      T.Continuation_param_aliases.extra_args_for_aliases =
        extra_args_for_aliases1;
      T.Continuation_param_aliases.recursive_continuation_wrapper =
        recursive_continuation_wrapper0
    }
  in
  res

(** val minimize_extra_args_for_aliases : T.Acc.t -> Simple.Set.t -> Simple.t
    Variable_.Map.t -> Variable.Set.t Continuation.Map.t -> t ->
    T.Continuation_param_aliases.t Continuation.Map.t coq_M **)

let minimize_extra_args_for_aliases source_info unboxed_blocks doms
    added_extra_args t0 =
  let available_added_extra_args =
    compute_added_extra_args added_extra_args t0
  in
  Continuation.Map.mapi
    (minimize_extra_args_for_one_continuation source_info unboxed_blocks
       available_added_extra_args doms)
    added_extra_args

(** val compute_continuation_extra_args_for_aliases : bool -> Name.Set.t ->
    T.Acc.t -> Simple.Set.t -> Simple.t Variable_.Map.t -> t ->
    T.Continuation_param_aliases.t Continuation.Map.t coq_M **)

let compute_continuation_extra_args_for_aliases speculative required_names
    source_info unboxed_blocks doms t0 =
  let added_extra_args =
    extra_args_for_aliases_overapproximation required_names source_info
      unboxed_blocks doms t0
  in
  let extra_args_for_toplevel_cont =
    Continuation.Map.find t0.dummy_toplevel_cont added_extra_args
  in
  let () =
    if
      (not speculative)
      && not (Variable.Set.is_empty extra_args_for_toplevel_cont)
    then
      Misc.fatal_errorf
        "ERROR:@\n\
         Toplevel continuation cannot have needed extra argument for aliases: \
         %a@."
        Variable.Set.print extra_args_for_toplevel_cont
    else ()
  in
  let extra_args_for_aliases0 =
    minimize_extra_args_for_aliases source_info unboxed_blocks doms
      added_extra_args t0
  in
  extra_args_for_aliases0

module Dot = struct
  (** val node_id : int -> Format.formatter -> Continuation.t -> unit coq_M **)

  let node_id ctx ppf cont =
    Format.fprintf ppf "node_%d_%d" ctx
      ((fun (x__1 : Continuation.t) -> (x__1 :> int)) cont)

  (** val node : Variable.Set.t option -> string option -> T.Acc.t ->
      (Format.formatter -> Continuation.t -> unit coq_M) -> int -> unit ->
      Format.formatter -> Continuation.t -> unit coq_M **)

  let node extra_args info df pp_node ctx _ ppf cont =
    let extra_args0 =
      match extra_args with
      | Some extra_args0 -> extra_args0
      | None -> Variable.Set.empty
    in
    let info0 = match info with Some info0 -> info0 | None -> "" in
    let params0, shape =
      match Continuation.Map.find_or_null cont df.Flow_types.Acc.map with
      | Null -> "[ none ]", ""
      | This elt ->
        let params0 =
          Format.asprintf "[%a]"
            ((fun x__1 x__2 x__3 x__4 ->
               Format.pp_print_list ?pp_sep:x__1 x__2 x__3 x__4)
               (Some (fun ppf0 _ -> Format.fprintf ppf0 ", "))
               Variable.print)
            (Bound_parameters.vars elt.Flow_types.Continuation_info.params)
        in
        let shape =
          if elt.Flow_types.Continuation_info.recursive
          then "shape=record"
          else ""
        in
        params0, shape
    in
    Format.fprintf ppf "%a [label=\"%a %s %s%s\" %s %s];@\n" (node_id ctx) cont
      Continuation.print cont params0
      (String.map
         (function '{' -> '[' | '}' -> ']' | c -> c)
         (Format.asprintf "%a" Variable.Set.print extra_args0))
      (String.map
         (function '{' -> '[' | '}' -> ']' | c -> c)
         (Format.asprintf "%a" pp_node cont))
      shape info0

  (** val nodes : T.Acc.t -> int -> Continuation.t -> Continuation.t ->
      T.Continuation_param_aliases.t Continuation.Map.t -> (Format.formatter ->
      Continuation.t -> unit coq_M) -> Format.formatter -> Continuation.Set.t ->
      unit coq_M **)

  let nodes df ctx return_continuation exn_continuation continuation_parameters
      pp_node ppf cont_map =
    Continuation.Set.iter
      (fun cont ->
        let extra_args =
          Option.map
            (fun continuation_parameters0 ->
              continuation_parameters0
                .Flow_types.Continuation_param_aliases.extra_args_for_aliases)
            (Continuation.Map.find_opt cont continuation_parameters)
        in
        let info =
          if Continuation.equal return_continuation cont
          then "color=blue"
          else if Continuation.equal exn_continuation cont
          then "color=red"
          else ""
        in
        node extra_args (Some info) df pp_node ctx () ppf cont)
      cont_map

  (** val edge : int -> string -> Format.formatter -> Continuation.t ->
      Continuation.t -> unit coq_M **)

  let edge ctx color ppf src dst =
    Format.fprintf ppf "%a -> %a [color=\"%s\"];@\n" (node_id ctx) dst
      (node_id ctx) src color

  (** val edges : int -> string -> Format.formatter -> Continuation.Set.t
      Continuation.Map.t -> unit coq_M **)

  let edges ctx color ppf edge_map =
    Continuation.Map.iter
      (fun src dst_set ->
        Continuation.Set.iter (fun dst -> edge ctx color ppf src dst) dst_set)
      edge_map

  (** val edges' : int -> string -> Format.formatter -> Continuation.t
      Continuation.Map.t -> unit coq_M **)

  let edges' ctx color ppf edge_map =
    Continuation.Map.iter (fun src dst -> edge ctx color ppf src dst) edge_map

  (** val print_ : int -> T.Acc.t -> string -> Format.formatter ->
      Continuation.t -> Continuation.t -> (Format.formatter -> Continuation.t ->
      unit coq_M) option -> T.Continuation_param_aliases.t Continuation.Map.t ->
      t -> unit coq_M **)

  let print_ ctx df print_name ppf return_continuation exn_continuation pp_node
      continuation_parameters t0 =
    let pp_node0 =
      match pp_node with Some pp_node0 -> pp_node0 | None -> fun _ _ -> ()
    in
    let dummy_toplevel_cont0 = t0.dummy_toplevel_cont in
    let all_conts =
      Continuation.Map.fold
        (fun cont callers0 acc ->
          Continuation.Set.add cont (Continuation.Set.union callers0 acc))
        t0.callers
        (Continuation.Set.of_list
           [dummy_toplevel_cont0; return_continuation; exn_continuation])
    in
    let all_conts0 =
      Continuation.Map.fold
        (fun cont _ acc -> Continuation.Set.add cont acc)
        t0.parents all_conts
    in
    Flambda_colours.without_colours (fun _ ->
        Format.fprintf ppf
          "subgraph cluster_%d { label=\"%s\";@\n%a%a@\n%a@\n%a@\n}@." ctx
          print_name
          (node None None df pp_node0 ctx ())
          dummy_toplevel_cont0
          (nodes df ctx return_continuation exn_continuation
             continuation_parameters pp_node0)
          all_conts0 (edges' ctx "green") t0.parents (edges ctx "black")
          t0.callers)

  (** val print : int -> T.Acc.t -> string -> Format.formatter -> Continuation.t
      -> Continuation.t -> (Format.formatter -> Continuation.t -> unit coq_M)
      option -> T.Continuation_param_aliases.t Continuation.Map.t -> t -> unit
      coq_M **)

  let print =
   fun ctx df print_name ppf return_continuation exn_continuation ?pp_node
       continuation_parameters t ->
    print_ ctx df print_name ppf return_continuation exn_continuation pp_node
      continuation_parameters t
end
