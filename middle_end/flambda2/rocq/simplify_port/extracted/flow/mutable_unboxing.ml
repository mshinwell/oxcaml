(** val find_alias : Dominator_graph.alias_map -> Simple.t -> Simple.t coq_M **)

let find_alias dom simple =
  Simple.pattern_match' simple
    (fun var _ ->
      match Variable.Map.find_or_null var dom with
      | Or_null.Null -> simple
      | Or_null.This res -> res)
    (fun _ _ -> simple)
    (fun _ -> simple)

(** val escaping_by_alias : Dominator_graph.alias_map -> Dominator_graph.t ->
