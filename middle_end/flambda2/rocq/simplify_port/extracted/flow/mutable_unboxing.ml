(** val escaping_by_return : Dominator_graph.alias_map -> T.Acc.t ->
    Continuation.t -> Continuation.t -> Simple.Set.t coq_M **)

let escaping_by_return dom source_info return_continuation exn_continuation =
  Continuation.Map.fold
    (fun _ elt escaping0 ->
      let add_escaping =
       fun cont escaping1 ->
        match
          Continuation.Map.find_or_null cont
            elt.Flow_types.Continuation_info.apply_cont_args
        with
        | Or_null.Null -> escaping1
        | Or_null.This apply_cont_args0 ->
          Variable.Set.fold
            (fun var escaping2 ->
              let escaping3 =
                match Variable.Map.find_or_null var dom with
                | Or_null.Null -> escaping2
                | Or_null.This simple -> Simple.Set.add simple escaping2
              in
              Simple.Set.add (Simple.var var) escaping3)
            (free_names_of_apply_cont_args apply_cont_args0)
            escaping1
      in
      let escaping1 = add_escaping return_continuation escaping0 in
      add_escaping exn_continuation escaping1)
    source_info.Flow_types.Acc.map Simple.Set.empty

(** val escaping : Dominator_graph.alias_map -> Dominator_graph.t -> T.Acc.t ->
    Continuation.t -> Continuation.t -> Name.Set.t -> Simple.Set.t coq_M **)

let escaping dom dom_graph source_info return_continuation exn_continuation
