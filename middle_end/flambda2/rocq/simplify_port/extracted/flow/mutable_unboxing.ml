(** val continuations_with_live_block : block_to_unbox Simple.Map.t ->
    Dominator_graph.alias_map -> T.Acc.t -> Control_flow_graph.t -> Simple.Set.t
    Continuation.Map.t coq_M **)

let continuations_with_live_block blocks_to_unbox0 dom source_info
    control_flow_graph =
  let continuations_defining_blocks0 =
    continuations_defining_blocks blocks_to_unbox0 source_info
  in
  let continuations_using_blocks0 =
    continuations_using_blocks blocks_to_unbox0 dom source_info
  in
  let continuations_using_blocks_but_not_defining_them =
    Continuation.Map.merge
      (fun _ defined0 used ->
        match defined0 with
        | Some defined1 -> (
          match used with
          | Some used0 -> Some (Simple.Set.diff used0 defined1)
          | None ->
            Misc.fatal_errorf
              "In Data_flow: incomplete map of continuation using blocks")
        | None -> (
          match used with
          | Some _ ->
            Misc.fatal_errorf
              "In Data_flow: incomplete map of continuation defining blocks"
          | None -> assert false))
      continuations_defining_blocks0 continuations_using_blocks0
  in
  Control_flow_graph.fixpoint control_flow_graph
    continuations_using_blocks_but_not_defining_them Simple.Set.equal
    (fun caller old_using_blocks _ used_blocks ->
      let defined_blocks =
        Continuation.Map.find caller continuations_defining_blocks0
      in
      Simple.Set.diff
        (Simple.Set.union old_using_blocks used_blocks)
        defined_blocks)

