                    (Named_rewrite.Prim_rewrite.invalid k))
                (fun bound_to ->
                  if Flambda_kind.equal (Simple.kind bound_to) k
                  then
                    Named_rewrite.prim_rewrite
                      (Named_rewrite.Prim_rewrite.replace_by_binding var
                         bound_to)
                  else
                    Named_rewrite.prim_rewrite
                      (Named_rewrite.Prim_rewrite.invalid k))
            in
            { bindings = env0.bindings;
              rewrites =
                Named_rewrite_id.Map.add rewrite_id rewrite env0.rewrites
            }))
      (fun _ block field value ->
        with_unboxed_fields block dom env0 (fun block0 fields ->
            let () =
              if Flambda_features.dump_flow ()
              then Format.printf "Remove Block set %a@." Variable.print var
              else ()
            in
            let rewrite, fields0 =
              Port_monad.match_exn
                (fun _ -> Numeric_types.Int.Map.find field fields)
                Port_monad.not_found
                (fun _ ->
                  ( Named_rewrite.prim_rewrite
                      (Named_rewrite.Prim_rewrite.invalid Flambda_kind.value),
                    fields ))
                (fun previous_value ->
                  if
                    Flambda_kind.equal
                      (Simple.kind previous_value)
                      (Simple.kind value)
                  then
                    ( Named_rewrite.prim_rewrite
                        Named_rewrite.Prim_rewrite.remove_prim,
                      Numeric_types.Int.Map.add field value fields )
                  else
                    ( Named_rewrite.prim_rewrite
                        (Named_rewrite.Prim_rewrite.invalid Flambda_kind.value),
                      fields ))
            in
            let rewrites0 =
              Named_rewrite_id.Map.add rewrite_id rewrite env0.rewrites
            in
            let bindings0 = Simple.Map.add block0 fields0 env0.bindings in
            { bindings = bindings0; rewrites = rewrites0 }))
      (fun _ _ _ fields ->
        if not (Simple.Map.mem (Simple.var var) blocks_to_unbox0)
        then env0
        else
          let () =
            if Flambda_features.dump_flow ()
            then Format.printf "Remove Makeblock %a@." Variable.print var
            else ()
          in
          let rewrite =
            Named_rewrite.prim_rewrite Named_rewrite.Prim_rewrite.remove_prim
          in
          let fields0 = list_to_int_map fields in
          let rewrites0 =
            Named_rewrite_id.Map.add rewrite_id rewrite env0.rewrites
          in
          let bindings0 =
            Simple.Map.add (Simple.var var) fields0 env0.bindings
          in
          { bindings = bindings0; rewrites = rewrites0 })
      prim0

  (** val init_env : block_to_unbox Simple.Map.t -> Simple.Set.t ->
      Named_rewrite.t Named_rewrite_id.Map.t -> (env * Bound_parameter.t list)
      coq_M **)

  let init_env blocks_to_unbox0 blocks_needed rewrites0 =
    let env0, params0 =
      Simple.Set.fold
        (fun block_needed pat ->
          let env0, params0 = pat in
          let { tag = _; mut = _; fields_kinds = fields_kinds0 } =
            Simple.Map.find block_needed blocks_to_unbox0
          in
          let block_params =
            List.mapi
              (fun i kind ->
                let name =
                  Simple.pattern_match' block_needed
                    (fun var _ -> Variable.canonical_name var)
                    (fun _ _ ->
                      Misc.fatal_errorf
                        "[Mutable Unboxing] Cannot unbox mutable symbols")
                    (fun _ ->
                      Misc.fatal_errorf
                        "[Mutable Unboxing] Cannot unbox constants")
                in
                let var =
                  (fun x__1 x__2 x__3 ->
                    Variable.create ?user_visible:x__1 x__2 x__3)
                    None
                    (Printf.sprintf "%s_%i" name i)
                    (Flambda_kind.With_subkind.kind kind)
                in
                let var_duid = Flambda_debug_uid.none in
                Bound_parameter.create var kind var_duid)
              fields_kinds0
          in
          let env1 =
            let fields =
              list_to_int_map
                (List.map
                   (fun bp -> Simple.var (Bound_parameter.var bp))
                   block_params)
            in
            { bindings = Simple.Map.add block_needed fields env0.bindings;
              rewrites = env0.rewrites
            }
          in
          env1, List.rev_append block_params params0)
        blocks_needed
        ({ bindings = Simple.Map.empty; rewrites = rewrites0 }, [])
    in
    env0, List.rev params0

  (** val append_int_map : 'a1 Numeric_types.Int.Map.t -> 'a1
      Numeric_types.Int.Map.t -> 'a1 Numeric_types.Int.Map.t coq_M **)

  let append_int_map i1 i2 =
    if Numeric_types.Int.Map.is_empty i1
    then i2
    else
      let max, _ = Numeric_types.Int.Map.max_binding i1 in
      let shifted_i2 =
        Numeric_types.Int.Map.map_keys (fun i -> i + max + 1) i2
      in
      (fun x__1 x__2 x__3 x__4 ->
        Numeric_types.Int.Map.disjoint_union ?eq:x__1 ?print:x__2 x__3 x__4)
        None None i1 shifted_i2

  (** val compute_rewrites : Target_system.Machine_width.t -> block_to_unbox
      Simple.Map.t -> Simple.Set.t Continuation.Map.t ->
      Dominator_graph.alias_map -> T.Acc.t -> ((extra_params * extra_args)
      Continuation.Map.t * Named_rewrite.t Named_rewrite_id.Map.t) coq_M **)

  let compute_rewrites machine_width blocks_to_unbox0
      continuations_with_live_block0 dom source_info =
    let rewrites0 = ref Named_rewrite_id.Map.empty in
    let extra_params_and_args0 =
      Continuation.Map.mapi
        (fun cont blocks_needed ->
          let elt = Continuation.Map.find cont source_info.Flow_types.Acc.map in
          let env0, extra_block_params =
            init_env blocks_to_unbox0 blocks_needed !rewrites0
          in
          let env1 =
            List.fold_left
              (fun env1 pat ->
                let { T.Mutable_let_prim.bound_var = bound_var0;
                      T.Mutable_let_prim.prim = prim0;
                      T.Mutable_let_prim.original_prim = _;
                      T.Mutable_let_prim.named_rewrite_id = named_rewrite_id0
                    } =
                  pat
                in
                apply_prim machine_width dom blocks_to_unbox0 env1
                  named_rewrite_id0 bound_var0 prim0)
              env0
              (List.rev elt.Flow_types.Continuation_info.mutable_let_prims_rev)
          in
          let () = rewrites0 := env1.rewrites in
          let blocks_params_to_add =
           fun cont0 rewrites1 ->
            Apply_cont_rewrite_id.Map.map
              (fun _ ->
                match
                  Continuation.Map.find_or_null cont0
                    continuations_with_live_block0
                with
                | Or_null.Null -> Numeric_types.Int.Map.empty
                | Or_null.This blocks_needed0 ->
                  let extra_args0 =
                    Simple.Set.fold
                      (fun block_needed extra_args0 ->
                        let args = Simple.Map.find block_needed env1.bindings in
                        append_int_map extra_args0 args)
                      blocks_needed0 Numeric_types.Int.Map.empty
                  in
                  extra_args0)
              rewrites1
          in
          let new_apply_cont_args =
            Continuation.Map.mapi blocks_params_to_add
              elt.Flow_types.Continuation_info.apply_cont_args
          in
          extra_block_params, new_apply_cont_args)
        continuations_with_live_block0
    in
    extra_params_and_args0, !rewrites0
end

(** val create : Dominator_graph.alias_map -> Dominator_graph.t -> T.Acc.t ->
    Control_flow_graph.t -> Name.Set.t -> Continuation.t -> Continuation.t ->
    Target_system.Machine_width.t -> t coq_M **)

let create dom dom_graph source_info control_flow_graph required_names0
    return_continuation exn_continuation machine_width =
  let escaping0 =
    escaping dom dom_graph source_info return_continuation exn_continuation
      required_names0
  in
  let blocks_to_unbox0 =
    blocks_to_unbox escaping0 source_info required_names0
  in
  let () =
    if
      (not (Simple.Map.is_empty blocks_to_unbox0))
      && Flambda_features.dump_flow ()
    then
      Format.printf "Non escaping makeblocks %a@."
        (Simple.Map.print (fun ppf pat ->
             let { tag = tag0; mut = mut0; fields_kinds = fields_kinds0 } =
               pat
             in
             Format.fprintf ppf "{%a}(%a)[%a]" Tag.print tag0 Mutability.print
               mut0
               ((fun x__1 x__2 x__3 x__4 ->
                  Format.pp_print_list ?pp_sep:x__1 x__2 x__3 x__4)
                  (Some Format.pp_print_space) Flambda_kind.With_subkind.print)
               fields_kinds0))
        blocks_to_unbox0
    else ()
  in
  let continuations_with_live_block0 =
    continuations_with_live_block blocks_to_unbox0 dom source_info
      control_flow_graph
  in
  let toplevel_used =
    Continuation.Map.find source_info.Flow_types.Acc.dummy_toplevel_cont
      continuations_with_live_block0
  in
  let () =
    if not (Simple.Set.is_empty toplevel_used)
    then
      Misc.fatal_errorf
        "Toplevel continuation cannot have needed extra argument for block: \
         %a@."
        Simple.Set.print toplevel_used
    else ()
  in
  let extra_params_and_args0, rewrites0 =
    Fold_prims.compute_rewrites machine_width blocks_to_unbox0
      continuations_with_live_block0 dom source_info
  in
  { blocks_to_unbox_ = blocks_to_unbox0;
    continuations_with_live_block_ = continuations_with_live_block0;
    extra_params_and_args = extra_params_and_args0;
    rewrites = rewrites0
  }

(** val pp_node : t -> Format.formatter -> Continuation.t -> unit coq_M **)

let pp_node t0 ppf cont =
  let { blocks_to_unbox_ = _;
        continuations_with_live_block_ = continuations_with_live_block0;
        extra_params_and_args = _;
        rewrites = _
      } =
    t0
  in
  match Continuation.Map.find_or_null cont continuations_with_live_block0 with
  | Or_null.Null -> ()
  | Or_null.This live_blocks ->
    Format.fprintf ppf " %a" Simple.Set.print live_blocks

(** val add_to_extra_params_and_args : t -> EPA.t Continuation.Map.t coq_M **)

let add_to_extra_params_and_args result =
  let epa = Continuation.Map.empty in
  let extra_block_args =
    Continuation.Map.fold
      (fun _ pat all_extra_args ->
        let _, extra_args0 = pat in
        Continuation.Map.fold
          (fun callee_cont caller_extra_args all_extra_args0 ->
            Continuation.Map.update callee_cont
              (fun previous_extra_args ->
                let previous_extra_args0 =
                  match previous_extra_args with
                  | Some extra_args1 -> extra_args1
                  | None -> (
                    match
                      Continuation.Map.find_or_null callee_cont
                        result.extra_params_and_args
                    with
                    | Or_null.Null -> []
                    | Or_null.This p ->
                      let extra_params0, _ = p in
                      List.map
                        (fun _ -> Apply_cont_rewrite_id.Map.empty)
                        extra_params0)
                in
                let extra_args1 =
                  Apply_cont_rewrite_id.Map.fold
                    (fun rewrite_id args previous_extra_args1 ->
                      let args0 = int_map_to_list args in
                      List.map2
                        (fun arg previous_extra_args2 ->
                          Apply_cont_rewrite_id.Map.add rewrite_id
                            (EPA.Extra_arg.Already_in_scope arg)
                            previous_extra_args2)
                        args0 previous_extra_args1)
                    caller_extra_args previous_extra_args0
                in
                Some extra_args1)
              all_extra_args0)
          extra_args0 all_extra_args)
      result.extra_params_and_args Continuation.Map.empty
  in
  let epa0 =
    Continuation.Map.fold
      (fun cont extra_args0 epa0 ->
        let extra_params0 =
          match
            Continuation.Map.find_or_null cont result.extra_params_and_args
          with
          | Or_null.Null -> []
          | Or_null.This p ->
            let extra_params0, _ = p in
            extra_params0
        in
        Continuation.Map.update cont
          (fun epa_for_cont ->
            let epa_for_cont0 =
              match epa_for_cont with Some epa1 -> epa1 | None -> EPA.empty
            in
            let epa_for_cont1 =
              List.fold_left2
                (fun epa_for_cont1 extra_param extra_args1 ->
                  EPA.add epa_for_cont1 Apply_cont_rewrite_id.Set.empty
                    extra_param extra_args1)
                epa_for_cont0 extra_params0 extra_args0
            in
            Some epa_for_cont1)
          epa0)
      extra_block_args epa
  in
  epa0

(** val did_unbox_a_mutable_block : t -> bool coq_M **)

let did_unbox_a_mutable_block result =
  Simple.Map.exists
    (fun _ block_to_unbox0 ->
      match block_to_unbox0.mut with
      | Mutability.Mutable -> true
      | Mutability.Immutable -> false
      | Mutability.Immutable_unique -> false)
    result.blocks_to_unbox_

(** val make_result : t -> (T.Mutable_unboxing_result.t * Simple.Set.t) coq_M **)

let make_result result =
  let additional_epa0 = add_to_extra_params_and_args result in
  let let_rewrites0 = result.rewrites in
  let did_unbox_a_mutable_block0 = did_unbox_a_mutable_block result in
  ( { T.Mutable_unboxing_result.did_unbox_a_mutable_block =
        did_unbox_a_mutable_block0;
      T.Mutable_unboxing_result.additional_epa = additional_epa0;
      T.Mutable_unboxing_result.let_rewrites = let_rewrites0
    },
    Simple.Map.keys result.blocks_to_unbox_ )
