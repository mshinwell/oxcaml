(** val escaping_by_use_for_one_continuation : Name.Set.t ->
    Dominator_graph.alias_map -> T.Continuation_info.t -> Simple.Set.t coq_M **)

let escaping_by_use_for_one_continuation required_names0 dom elt =
  let add_name_occurrences =
   fun occurrences init ->
    Name_occurrences.fold_variables occurrences init (fun escaping0 var ->
        let escaping1 =
          match Variable.Map.find_or_null var dom with
          | Or_null.Null -> escaping0
          | Or_null.This simple -> Simple.Set.add simple escaping0
        in
        Simple.Set.add (Simple.var var) escaping1)
  in
  let escaping0 =
    add_name_occurrences elt.Flow_types.Continuation_info.used_in_handler
      Simple.Set.empty
  in
  let escaping1 =
    Name.Map.fold
      (fun name deps escaping1 ->
        if Name.Set.mem name required_names0
        then add_name_occurrences deps escaping1
        else escaping1)
      elt.Flow_types.Continuation_info.bindings escaping0
  in
  let escaping2 =
    Variable.Set.fold
      (fun var escaping2 ->
        match Variable.Map.find_or_null var dom with
        | Or_null.Null -> escaping2
        | Or_null.This simple -> Simple.Set.add simple escaping2)
      (names_used_in_new_let_binding elt)
      escaping1
  in
  let escaping3 =
    Value_slot.Map.fold
      (fun _ map0 escaping3 ->
        Name.Map.fold (fun _ -> add_name_occurrences) map0 escaping3)
      elt.Flow_types.Continuation_info.value_slots escaping2
  in
  let escaping4 =
    List.fold_left
      (fun escaping4 pat ->
        let { T.Mutable_let_prim.bound_var = bound_var0;
              T.Mutable_let_prim.prim = prim0;
              T.Mutable_let_prim.original_prim = _;
              T.Mutable_let_prim.named_rewrite_id = _
            } =
          pat
        in
        let result_required =
          Name.Set.mem (Name.var bound_var0) required_names0
        in
        add_name_occurrences
          (names_escaping_from_mutable_prim result_required prim0)
          escaping4)
      escaping3 elt.Flow_types.Continuation_info.mutable_let_prims_rev
  in
  escaping4

