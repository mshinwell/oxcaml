let escaping_by_alias dom dom_graph =
  Simple.Map.fold
    (fun flow_to flow_from escaping0 ->
      let alias_to = find_alias dom flow_to in
      let new_escaping =
        Simple.Set.fold
          (fun flow_from0 escaping1 ->
            let alias_from = find_alias dom flow_from0 in
            let is_escaping = not (Simple.equal alias_to alias_from) in
            if is_escaping
