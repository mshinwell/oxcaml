open Port_monad

type t =
  { params : Bound_parameters.t;
    continuation : Continuation.t;
    args : Simple.t list
  }

(** val params : t -> Bound_parameters.t **)

let params t0 = t0.params

(** val continuation : t -> Continuation.t **)

let continuation t0 = t0.continuation

(** val args : t -> Simple.t list **)

let args t0 = t0.args

(** val print : Format.formatter -> t -> unit coq_M **)

let print ppf pat =
  let { params = params0; continuation = continuation0; args = args0 } = pat in
  Format.fprintf ppf
    "@[<hov 1>(@[<hov 1>(params@ %a)@]@ @[<hov 1>(continuation@ %a)@]@ @[<hov \
     1>(args@ %a)@])@]"
    Bound_parameters.print params0 Continuation.print continuation0
    ((fun x__1 x__2 x__3 x__4 ->
       Format.pp_print_list ?pp_sep:x__1 x__2 x__3 x__4)
       (Some (fun ppf0 _ -> Format.fprintf ppf0 ",@ "))
       Simple.print)
    args0

(** val create : Bound_parameters.t -> Continuation.t -> Simple.t list -> t
    coq_M **)

let create params0 continuation0 args0 =
  { params = params0; continuation = continuation0; args = args0 }

(** val apply : t -> Simple.t list -> (Continuation.t * Simple.t list) coq_M **)

let apply t0 shortcut_args =
  let { params = params0; continuation = continuation0; args = args0 } = t0 in
  let subst =
    List.fold_left2
      (fun subst param arg -> Variable.Map.add param arg subst)
      Variable.Map.empty
      (Bound_parameters.vars params0)
      shortcut_args
  in
  ( continuation0,
    List.map
      (fun arg ->
        Simple.pattern_match' arg
          (fun var coercion ->
            match Variable.Map.find_or_null var subst with
            | Or_null.Null -> arg
            | Or_null.This simple -> Simple.apply_coercion_exn simple coercion)
          (fun _ _ -> arg)
          (fun _ -> arg))
      args0 )

(** val to_alias : t -> Continuation.t option coq_M **)

let to_alias t0 =
  let params0 = Bound_parameters.simples t0.params in
  if Misc.Stdlib.List.equal Simple.equal t0.args params0
  then Some t0.continuation
  else None
