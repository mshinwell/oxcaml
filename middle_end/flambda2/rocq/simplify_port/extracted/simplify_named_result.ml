open! Flambda.Import
open Port_monad

type t =
  { dacc : Downwards_acc.t;
    bindings_to_place : Simplified_named.binding_to_place list;
    was_lifted_set_of_closures : bool
  }

(** val dacc : t -> Downwards_acc.t **)

let dacc t0 = t0.dacc

(** val bindings_to_place : t -> Simplified_named.binding_to_place list **)

let bindings_to_place t0 = t0.bindings_to_place

(** val was_lifted_set_of_closures : t -> bool **)

let was_lifted_set_of_closures t0 = t0.was_lifted_set_of_closures

(** val with_dacc : Downwards_acc.t -> t -> t coq_M **)

let with_dacc dacc0 t0 =
  { dacc = dacc0;
    bindings_to_place = t0.bindings_to_place;
    was_lifted_set_of_closures = t0.was_lifted_set_of_closures
  }

(** val create : Downwards_acc.t -> Simplified_named.binding_to_place -> t coq_M
    **)

let create dacc0 binding_to_place =
  { dacc = dacc0;
    bindings_to_place = binding_to_place :: [];
    was_lifted_set_of_closures = false
  }

(** val create_empty : Downwards_acc.t -> t coq_M **)

let create_empty dacc0 =
  { dacc = dacc0; bindings_to_place = []; was_lifted_set_of_closures = false }

(** val create_have_lifted_set_of_closures : Downwards_acc.t -> (Bound_var.t *
    Symbol.t) list -> Flambda.Import.Named.t -> t coq_M **)

let create_have_lifted_set_of_closures dacc0 bound_vars_to_symbols
    original_defining_expr =
  let machine_width = Downwards_env.machine_width (Downwards_acc.denv dacc0) in
  { dacc = dacc0;
    bindings_to_place =
      List.mapi
        (fun i pat ->
          let var, sym = pat in
          (fun (x__1, x__2, x__3) ->
            (Simplified_named.Keep_binding
               { let_bound = x__1;
                 simplified_defining_expr = x__2;
                 original_defining_expr = x__3
               }
              : Simplified_named.binding_to_place))
            ( Bound_pattern.singleton var,
              Simplified_named.create machine_width
                (Flambda.Import.Named.create_simple (Simple.symbol sym)),
              if i = 0 then Some original_defining_expr else None ))
        bound_vars_to_symbols;
    was_lifted_set_of_closures = true
  }

(** val no_bindings : t -> bool coq_M **)

let no_bindings t0 =
  match t0.bindings_to_place with [] -> true | _ :: _ -> false
