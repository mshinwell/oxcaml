        Downwards_env.defined_variables_by_scope env_at_use
      in
      let args =
        Lifted_cont_params.args callee_lifted_params caller_stack_lifted_params
      in
      let lifted_arg_types =
        List.map2
          (fun arg param ->
            let typing_env0 = Downwards_env.typing_env env_at_use in
