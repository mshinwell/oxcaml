(* Extraction of the machine of FlambdaSemanticsSpec.v, of the comparison
   of FlambdaCompareSpec.v and of the normalisations of
   FlambdaNormaliseSpec.v and ../types/rocq/FlambdaAliasesSpec.v to OCaml,
   for testing:
   middle_end/flambda2/tests/semantics/ runs terms before and after
   Simplify on the machine and compares what they come to, and compares
   the terms themselves.

   This file is to be reviewed with that test tool, and matters only to
   it: no part of the compiler is built from what is extracted here. The
   extracted modules are committed, in tests/semantics/extracted/, and are
   regenerated by rocq/Makefile.

   Nothing of the model is realised by hand-written OCaml: the
   primitives, their evaluation and their equality test are extracted
   like the rest (FlambdaPrimitiveModel.v, FlambdaPrimitiveSpec.v).

   The finite maps and the sets of names of FlambdaMapSpec.v are extracted
   in full, used by the machine or not, so that tests of what is built on
   them have them. Of its module [Keyed], for other keys, nothing is in
   the list yet: an operation of it is added when a test tool asks.

   [bool], [option], [list], pairs and [unit] are extracted to OCaml's own
   (ExtrOcamlBasic); the numbers are extracted as they are, binary. *)

From Stdlib Require Extraction.
From Stdlib Require Import ExtrOcamlBasic.
From OxCamlFlambda2 Require Import FlambdaMapSpec FlambdaModel
  FlambdaBindersSpec FlambdaSemanticsSpec FlambdaWellFormedSpec
  FlambdaWellKindedSpec
  FlambdaCompareSpec FlambdaNormaliseSpec FlambdaBlockLoadSpec
  FlambdaUnboxSpec FlambdaUnusedContsSpec FlambdaUnusedStaticsSpec
  FlambdaValidateSpec.
From OxCamlFlambda2Types Require Import FlambdaAliasesSpec.

Extraction Language OCaml.

(* A type with one constructor of one argument stays a type of its own,
   so that the OCaml that builds terms of the model does not change shape
   when such a type gains a constructor. *)
Set Extraction KeepSingleton.

(* The Makefile runs this from the directory the modules go into. *)
Set Extraction Output Directory ".".

(* What is extracted, with all it uses: one name to a line, in alphabetical
   order, so that branches that each add a name merge. The order means
   nothing, and the closing full stop has a line of its own for the same
   reason. *)
Separate Extraction
  all_among
  among
  at_partial_or_over_application
  bind_closures
  binders_distinct
  code_closed
  collapse_switches
  compact
  dedup
  distinct
  domain
  drop_deleted_code
  drop_statics
  empty_static_env
  expr_eqb
  filter_bindings
  fold_constants
  follow_aliases
  inline_calls
  inline_known_calls
  inline_tail_conts
  inter
  inter_with
  is_bound
  kind_of_const
  let_closures
  load_known_blocks
  lookup
  make_code_metadata
  make_exn_handler_metadata
  make_handler_metadata
  map_values
  merge
  merge_statics
  names_in_scope
  numbers_in_range
  partial_or_over_application
  remove_unused_conts
  remove_unused_defined_lets
  remove_unused_lets
  remove_unused_total_lets
  rewrite_code
  run
  step
  traps_well_formed
  unarize
  unbind
  unbox_known_numbers
  union_with
  unit_exn_handlers_well_formed
  validate_unit
  well_formed_unit
  well_kinded_unit
  without
  .
